use anyhow::Result;
use serde::{Deserialize, Serialize};
use sqlx::{PgConnection, Row};

const TABLES_QUERY: &str = "SELECT t.table_name,
                obj_description(c.oid, 'pg_class') AS comment
         FROM information_schema.tables t
         JOIN pg_catalog.pg_namespace n
           ON n.nspname = t.table_schema
         JOIN pg_catalog.pg_class c
           ON c.relname = t.table_name
          AND c.relnamespace = n.oid
          AND c.relkind = 'r'
         LEFT JOIN pg_catalog.pg_depend d
           ON d.classid = 'pg_class'::regclass
          AND d.objid = c.oid
          AND d.deptype = 'e'
         WHERE t.table_schema = $1
           AND t.table_type = 'BASE TABLE'
           AND t.table_name NOT LIKE '\\_platform%'
           AND d.objid IS NULL
         ORDER BY t.table_name";

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DbTable {
    pub schema: String,
    pub name: String,
    pub columns: Vec<DbColumn>,
    /// The table's `COMMENT ON TABLE`, which is where Supatype records ownership.
    ///
    /// Read so the differ can tell a table it created from one it merely found. Without it,
    /// pointing a push at someone else's database dropped every table not in the schema.
    #[serde(default)]
    pub comment: Option<String>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DbColumn {
    pub name: String,
    pub data_type: String,
    pub udt_name: String,
    pub nullable: bool,
    pub default: Option<String>,
    pub ordinal_position: i32,
    /// `numeric_precision` and `numeric_scale`, which `data_type` does not carry.
    ///
    /// `information_schema.columns.data_type` for `NUMERIC(5, 2)` is the bare string `numeric`:
    /// the precision and the scale are separate columns. The differ compared `data_type` against
    /// a rendered `numeric(5,2)` and so never matched, which made every `Decimal<p, s>` column
    /// report a type change on every diff. The generated `ALTER` was a no-op the database would
    /// have accepted and ignored, except where a view depends on the column, where Postgres
    /// refuses with `cannot alter type of a column used by a view or rule` - so a schema pairing
    /// `Decimal` with `versions: { drafts: true }` could be pushed once and never again.
    #[serde(default)]
    pub numeric_precision: Option<i32>,
    #[serde(default)]
    pub numeric_scale: Option<i32>,
    /// `GENERATED ... AS IDENTITY`: the database numbers the column from the sequence it owns.
    /// This and the three below are left out of the JSON when unset, so a plain column reads (and a
    /// snapshot of one is written) as it was before they were read.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub is_identity: bool,
    /// `ALWAYS` or `BY DEFAULT` for an identity column, as `information_schema` spells it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub identity_generation: Option<String>,
    /// `GENERATED ALWAYS AS (...) STORED`: the database computes the column from the row.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub is_generated: bool,
    /// A generated column's expression, as Postgres deparses it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub generation_expression: Option<String>,
}

impl DbColumn {
    /// How the database fills the column, in the words of its definition: `GENERATED ALWAYS AS
    /// IDENTITY`, `GENERATED BY DEFAULT AS IDENTITY`, `GENERATED ALWAYS AS (expr) STORED`, or
    /// nothing. An identity or generated column has no default, so the column's fingerprint carries
    /// this in the default's place and a plain column's fingerprint is what it always was.
    pub fn generation(&self) -> Option<String> {
        if self.is_identity {
            let how = self.identity_generation.as_deref().unwrap_or("ALWAYS");
            return Some(format!("GENERATED {how} AS IDENTITY"));
        }
        if self.is_generated {
            let expression = self.generation_expression.as_deref().unwrap_or_default();
            return Some(format!("GENERATED ALWAYS AS ({expression}) STORED"));
        }
        None
    }
}

pub async fn read(conn: &mut PgConnection, schema: &str) -> Result<Vec<DbTable>> {
    let table_rows: Vec<(String, Option<String>)> = sqlx::query_as(TABLES_QUERY)
        .bind(schema)
        .fetch_all(&mut *conn)
        .await?;

    let mut tables = Vec::new();
    for (name, comment) in table_rows {
        let columns = read_columns(conn, schema, &name).await?;
        tables.push(DbTable {
            schema: schema.to_string(),
            name,
            columns,
            comment,
        });
    }
    Ok(tables)
}

async fn read_columns(conn: &mut PgConnection, schema: &str, table: &str) -> Result<Vec<DbColumn>> {
    let rows = sqlx::query(
        "SELECT column_name::text, data_type::text, udt_name::text, is_nullable::text,
                column_default::text, ordinal_position::int4, numeric_precision::int4,
                numeric_scale::int4, is_identity::text, identity_generation::text,
                is_generated::text, generation_expression::text
         FROM information_schema.columns
         WHERE table_schema = $1 AND table_name = $2
         ORDER BY ordinal_position",
    )
    .bind(schema)
    .bind(table)
    .fetch_all(&mut *conn)
    .await?;

    rows.into_iter()
        .map(|row| {
            let is_identity: Option<String> = row.try_get(8)?;
            let is_generated: Option<String> = row.try_get(10)?;
            Ok(DbColumn {
                name: row.try_get(0)?,
                data_type: row.try_get(1)?,
                udt_name: row.try_get(2)?,
                nullable: row.try_get::<String, _>(3)? == "YES",
                default: row.try_get(4)?,
                ordinal_position: row.try_get(5)?,
                numeric_precision: row.try_get(6)?,
                numeric_scale: row.try_get(7)?,
                is_identity: is_identity.as_deref() == Some("YES"),
                identity_generation: row.try_get(9)?,
                is_generated: is_generated.as_deref() == Some("ALWAYS"),
                generation_expression: row.try_get(11)?,
            })
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::TABLES_QUERY;

    #[test]
    fn table_query_excludes_extension_owned_tables() {
        assert!(TABLES_QUERY.contains("LEFT JOIN pg_catalog.pg_depend d"));
        assert!(TABLES_QUERY.contains("d.deptype = 'e'"));
        assert!(TABLES_QUERY.contains("d.objid IS NULL"));
    }
}
