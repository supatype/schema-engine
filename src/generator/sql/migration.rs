use crate::differ::{DiffOutput, Operation, Risk};
use crate::parser::ast::{
    DefaultValueAst, FieldAst, IndexAst, IndexMethod, ModelAst, RelationCardinality,
    RelationFieldAst, ScalarFieldAst,
};
use anyhow::{bail, Result};
use sha2::{Digest, Sha256};

/// Returns only the forward (apply) SQL — suitable for execution against a live DB.
pub fn forward_sql(diff: &DiffOutput, force: bool) -> Result<String> {
    if diff.summary.is_destructive && !force {
        bail!(
            "{} destructive operation(s) detected. Use --force to proceed.",
            diff.summary.destructive
        );
    }
    render_forward(diff)
}

/// Returns the full migration file (forward + rollback) for saving to disk.
pub fn generate(diff: &DiffOutput, force: bool) -> Result<String> {
    if diff.summary.is_destructive && !force {
        bail!(
            "{} destructive operation(s) detected. Use --force to proceed.",
            diff.summary.destructive
        );
    }

    let forward = render_forward(diff)?;
    let rollback = super::rollback::generate(diff)?;
    let hash = migration_hash(&forward);

    Ok(format!(
        "-- Migration generated by supatype-engine v{ver}\n\
         -- Hash: {hash}\n\
         -- Risk: {risk}\n\n\
         {forward}\n\n\
         {rollback}",
        ver = env!("ENGINE_VERSION"),
        risk = if diff.summary.is_destructive {
            "destructive"
        } else if diff.summary.cautious > 0 {
            "cautious"
        } else {
            "safe"
        },
    ))
}

fn needs_pgcrypto(diff: &DiffOutput) -> bool {
    use crate::parser::ast::FieldAst;
    let uuid_default = |f: &FieldAst| {
        matches!(f,
            FieldAst::Uuid(s) if matches!(&s.default, Some(DefaultValueAst::GenRandomUuid))
        )
    };
    diff.operations.iter().any(|op| match op {
        Operation::CreateTable { model, .. } => model.fields.values().any(uuid_default),
        Operation::AddColumn { field, .. } => uuid_default(field),
        _ => false,
    })
}

fn render_forward(diff: &DiffOutput) -> Result<String> {
    let mut lines = vec![
        "-- ============================================================".into(),
        "-- FORWARD MIGRATION".into(),
        "-- ============================================================".into(),
        String::new(),
    ];

    if needs_pgcrypto(diff) {
        lines.push("CREATE EXTENSION IF NOT EXISTS \"pgcrypto\";".into());
        lines.push(String::new());
    }

    lines.push("BEGIN;".into());
    lines.push(String::new());

    for op in &diff.operations {
        let risk_label = match op {
            Operation::CreateTable { risk, .. }
            | Operation::DropTable { risk, .. }
            | Operation::AddColumn { risk, .. }
            | Operation::DropColumn { risk, .. }
            | Operation::RenameColumn { risk, .. }
            | Operation::AlterColumn { risk, .. }
            | Operation::AddIndex { risk, .. }
            | Operation::DropIndex { risk, .. }
            | Operation::AddForeignKey { risk, .. }
            | Operation::DropForeignKey { risk, .. }
            | Operation::CreateEnum { risk, .. }
            | Operation::DropEnum { risk, .. }
            | Operation::AddEnumValue { risk, .. }
            | Operation::RemoveEnumValue { risk, .. }
            | Operation::RenameEnumValue { risk, .. }
            | Operation::ReorderEnumValues { risk, .. }
            | Operation::EnableRls { risk, .. }
            | Operation::CreateRlsPolicy { risk, .. }
            | Operation::DropRlsPolicy { risk, .. }
            | Operation::CreateTrigger { risk, .. }
            | Operation::DropTrigger { risk, .. }
            | Operation::CreateJunctionTable { risk, .. }
            | Operation::EnableExtension { risk, .. } => match risk {
                Risk::Safe => "safe",
                Risk::Cautious => "cautious",
                Risk::Destructive => "destructive",
            },
        };

        let sql = render_operation(op)?;
        lines.push(format!(
            "-- [{risk_label}] {desc}",
            desc = op_description(op)
        ));
        lines.push(sql);
        lines.push(String::new());
    }

    lines.push("COMMIT;".into());
    Ok(lines.join("\n"))
}

fn op_description(op: &Operation) -> String {
    match op {
        Operation::CreateTable { table, .. } => format!("Create table: {table}"),
        Operation::DropTable { table, .. } => format!("Drop table: {table}"),
        Operation::AddColumn { table, column, .. } => format!("Add column: {table}.{column}"),
        Operation::DropColumn { table, column, .. } => format!("Drop column: {table}.{column}"),
        Operation::RenameColumn {
            table, from, to, ..
        } => format!("Rename column: {table}.{from} → {to}"),
        Operation::AlterColumn { table, column, .. } => format!("Alter column: {table}.{column}"),
        Operation::AddIndex { table, index, .. } => {
            format!("Add index on: {table}({})", index.fields.join(", "))
        }
        Operation::DropIndex { index_name, .. } => format!("Drop index: {index_name}"),
        Operation::AddForeignKey {
            table, relation, ..
        } => format!("Add FK: {table} → {}", relation.target),
        Operation::DropForeignKey {
            table, constraint, ..
        } => format!("Drop FK: {table}.{constraint}"),
        Operation::CreateEnum { name, .. } => format!("Create enum: {name}"),
        Operation::DropEnum { name, .. } => format!("Drop enum: {name}"),
        Operation::AddEnumValue {
            enum_name, value, ..
        } => format!("Add enum value: {enum_name}.'{value}'"),
        Operation::RemoveEnumValue {
            enum_name, value, ..
        } => format!("Remove enum value: {enum_name}.'{value}'"),
        Operation::RenameEnumValue {
            enum_name,
            from,
            to,
            ..
        } => format!("Rename enum value: {enum_name}.'{from}' \u{2192} '{to}'"),
        Operation::ReorderEnumValues { enum_name, .. } => {
            format!("Reorder enum values: {enum_name}")
        }
        Operation::EnableRls { table, .. } => format!("Enable RLS: {table}"),
        Operation::CreateRlsPolicy { table, policy, .. } => {
            format!("Create RLS policy: {table}.{policy}")
        }
        Operation::DropRlsPolicy { table, policy, .. } => {
            format!("Drop RLS policy: {table}.{policy}")
        }
        Operation::CreateTrigger { table, trigger, .. } => {
            format!("Create trigger: {table}.{trigger}")
        }
        Operation::DropTrigger { table, trigger, .. } => format!("Drop trigger: {table}.{trigger}"),
        Operation::CreateJunctionTable { table, .. } => format!("Create junction table: {table}"),
        Operation::EnableExtension { name, .. } => format!("Enable extension: {name}"),
    }
}

fn render_operation(op: &Operation) -> Result<String> {
    match op {
        Operation::CreateTable { model, .. } => create_table_sql(model),
        Operation::DropTable { table, .. } => Ok(format!(
            "DROP TABLE IF EXISTS \"public\".\"{table}\" CASCADE;"
        )),
        Operation::AddColumn {
            table,
            column,
            field,
            ..
        } => {
            let col_def = field_to_column_def(column, field)?;
            Ok(format!(
                "ALTER TABLE \"public\".\"{table}\" ADD COLUMN {col_def};"
            ))
        }
        Operation::DropColumn { table, column, .. } => Ok(format!(
            "ALTER TABLE \"public\".\"{table}\" DROP COLUMN IF EXISTS \"{column}\";"
        )),
        Operation::RenameColumn {
            table, from, to, ..
        } => Ok(format!(
            "ALTER TABLE \"public\".\"{table}\" RENAME COLUMN \"{from}\" TO \"{to}\";"
        )),
        Operation::AlterColumn {
            table,
            column,
            changes,
            ..
        } => alter_column_sql(table, column, changes),
        Operation::AddIndex { table, index, .. } => create_index_sql(table, index),
        Operation::DropIndex { index_name, .. } => {
            Ok(format!("DROP INDEX IF EXISTS \"{index_name}\";"))
        }
        Operation::AddForeignKey {
            table,
            relation,
            ref_table,
            ..
        } => add_fk_sql(table, relation, ref_table),
        Operation::DropForeignKey {
            table, constraint, ..
        } => Ok(format!(
            "ALTER TABLE \"public\".\"{table}\" DROP CONSTRAINT IF EXISTS \"{constraint}\";"
        )),
        Operation::CreateEnum { name, values, .. } => {
            let vals = values
                .iter()
                .map(|v| format!("'{v}'"))
                .collect::<Vec<_>>()
                .join(", ");
            Ok(format!("CREATE TYPE \"{name}\" AS ENUM ({vals});"))
        }
        Operation::DropEnum { name, .. } => Ok(format!("DROP TYPE IF EXISTS \"{name}\";")),
        // Task 67: Add enum value — Postgres 12+ supports this inside transactions.
        Operation::AddEnumValue {
            enum_name, value, ..
        } => Ok(format!(
            "ALTER TYPE \"{enum_name}\" ADD VALUE '{value}';"
        )),
        // Task 68: Remove enum value — Postgres has no ALTER TYPE ... REMOVE VALUE.
        // Strategy: rename old type → create new type without value → alter columns → drop old.
        Operation::RemoveEnumValue {
            enum_name,
            value,
            affected_columns,
            ..
        } => {
            let old_name = format!("{enum_name}_old");
            let mut stmts = Vec::new();

            // 1. Pre-flight check: warn/fail if rows use this value
            for (table, column) in affected_columns {
                stmts.push(format!(
                    "DO $$ BEGIN\n  \
                     IF EXISTS (SELECT 1 FROM \"public\".\"{table}\" WHERE \"{column}\"::text = '{value}') THEN\n    \
                     RAISE WARNING 'Rows in {table}.{column} still use enum value ''{value}''. Update them before applying.';\n  \
                     END IF;\n\
                     END $$;"
                ));
            }

            // 2. Rename old type
            stmts.push(format!(
                "ALTER TYPE \"{enum_name}\" RENAME TO \"{old_name}\";"
            ));

            // 3. We need the new values — they are all old values minus the removed one.
            //    Since we don't carry the full old values list in RemoveEnumValue,
            //    we build the new type dynamically from pg_enum.
            stmts.push(format!(
                "DO $$ \n\
                 DECLARE\n  \
                   _vals text;\n\
                 BEGIN\n  \
                   SELECT string_agg(quote_literal(enumlabel), ', ' ORDER BY enumsortorder)\n  \
                     INTO _vals\n  \
                     FROM pg_enum\n  \
                     JOIN pg_type ON pg_type.oid = pg_enum.enumtypid\n  \
                    WHERE pg_type.typname = '{old_name}'\n  \
                      AND enumlabel != '{value}';\n  \
                   EXECUTE format('CREATE TYPE \"{enum_name}\" AS ENUM (%s)', _vals);\n\
                 END $$;"
            ));

            // 4. Alter columns to use the new type
            for (table, column) in affected_columns {
                stmts.push(format!(
                    "ALTER TABLE \"public\".\"{table}\" ALTER COLUMN \"{column}\" \
                     TYPE \"{enum_name}\" USING \"{column}\"::text::\"{enum_name}\";"
                ));
            }

            // 5. Drop the old type
            stmts.push(format!("DROP TYPE \"{old_name}\";"));

            Ok(stmts.join("\n"))
        }
        // Task 69: Rename enum value — Postgres 10+ native support.
        Operation::RenameEnumValue {
            enum_name,
            from,
            to,
            ..
        } => Ok(format!(
            "ALTER TYPE \"{enum_name}\" RENAME VALUE '{from}' TO '{to}';"
        )),
        // Task 70: Reorder enum values — must recreate the type since Postgres
        // enum ordering is determined by creation order.
        Operation::ReorderEnumValues {
            enum_name,
            new_values,
            affected_columns,
            ..
        } => {
            let old_name = format!("{enum_name}_old");
            let vals = new_values
                .iter()
                .map(|v| format!("'{v}'"))
                .collect::<Vec<_>>()
                .join(", ");

            let mut stmts = Vec::new();

            // 1. Rename old type
            stmts.push(format!(
                "ALTER TYPE \"{enum_name}\" RENAME TO \"{old_name}\";"
            ));

            // 2. Create new type with desired order
            stmts.push(format!(
                "CREATE TYPE \"{enum_name}\" AS ENUM ({vals});"
            ));

            // 3. Alter all columns to use the new type
            for (table, column) in affected_columns {
                stmts.push(format!(
                    "ALTER TABLE \"public\".\"{table}\" ALTER COLUMN \"{column}\" \
                     TYPE \"{enum_name}\" USING \"{column}\"::text::\"{enum_name}\";"
                ));
            }

            // 4. Drop old type
            stmts.push(format!("DROP TYPE \"{old_name}\";"));

            Ok(stmts.join("\n"))
        }
        Operation::EnableRls { table, .. } => Ok(format!(
            "ALTER TABLE \"public\".\"{table}\" ENABLE ROW LEVEL SECURITY;"
        )),
        Operation::CreateRlsPolicy { table, policy, .. } => Ok(format!(
            "-- RLS policy '{policy}' on '{table}' — run: supatype-engine rls"
        )),
        Operation::DropRlsPolicy { table, policy, .. } => Ok(format!(
            "DROP POLICY IF EXISTS \"{policy}\" ON \"public\".\"{table}\";"
        )),
        Operation::CreateTrigger { table, trigger, .. } => Ok(format!(
            "-- Trigger '{trigger}' on '{table}' — run: supatype-engine generate (triggers)"
        )),
        Operation::DropTrigger { table, trigger, .. } => Ok(format!(
            "DROP TRIGGER IF EXISTS \"{trigger}\" ON \"public\".\"{table}\";"
        )),
        Operation::CreateJunctionTable {
            table,
            fk_a,
            table_a,
            fk_b,
            table_b,
            ..
        } => {
            let table_a_snake = to_snake_case(table_a);
            let table_b_snake = to_snake_case(table_b);
            Ok(format!(
                "CREATE TABLE IF NOT EXISTS \"public\".\"{table}\" (\n    \
                 \"{fk_a}\" UUID NOT NULL REFERENCES \"public\".\"{table_a_snake}\" (\"id\") ON DELETE CASCADE,\n    \
                 \"{fk_b}\" UUID NOT NULL REFERENCES \"public\".\"{table_b_snake}\" (\"id\") ON DELETE CASCADE,\n    \
                 PRIMARY KEY (\"{fk_a}\", \"{fk_b}\")\n\
                 );"
            ))
        }
        Operation::EnableExtension { name, .. } => {
            Ok(format!("CREATE EXTENSION IF NOT EXISTS \"{name}\";"))
        }
    }
}

// ─── CREATE TABLE ────────────────────────────────────────────────────────────

fn create_table_sql(model: &ModelAst) -> Result<String> {
    let table = &model.table_name;
    let mut col_defs: Vec<String> = Vec::new();

    for (field_name, field) in &model.fields {
        match field {
            FieldAst::Relation(rel) => {
                if matches!(rel.cardinality, RelationCardinality::BelongsTo) {
                    let fk_col = rel
                        .foreign_key
                        .as_deref()
                        .unwrap_or_else(|| Box::leak(format!("{field_name}_id").into_boxed_str()));
                    let uniq = if rel.unique_fk { " UNIQUE" } else { "" };
                    col_defs.push(format!("    \"{fk_col}\" UUID{uniq}"));
                    // FK constraint is a separate AddForeignKey operation (emitted after all tables).
                }
                // hasMany / hasOne / manyToMany produce no column here
            }
            FieldAst::Timestamps => {
                col_defs.push("    \"created_at\" TIMESTAMPTZ NOT NULL DEFAULT NOW()".into());
                col_defs.push("    \"updated_at\" TIMESTAMPTZ NOT NULL DEFAULT NOW()".into());
            }
            FieldAst::Publishable => {
                col_defs.push("    \"status\" TEXT NOT NULL DEFAULT 'draft' CHECK (\"status\" IN ('draft', 'published', 'scheduled', 'archived'))".into());
                col_defs.push("    \"published_at\" TIMESTAMPTZ".into());
                col_defs.push("    \"scheduled_at\" TIMESTAMPTZ".into());
            }
            FieldAst::SoftDelete => {
                col_defs.push("    \"deleted_at\" TIMESTAMPTZ".into());
            }
            other => {
                col_defs.push(format!("    {}", field_to_column_def(field_name, other)?));
            }
        }
    }

    // Timestamps from options (if not already added as composite field)
    if model.options.timestamps && !model.fields.contains_key("timestamps") {
        let has_created =
            model.fields.contains_key("created_at") || model.fields.contains_key("createdAt");
        let has_updated =
            model.fields.contains_key("updated_at") || model.fields.contains_key("updatedAt");
        if !has_created {
            col_defs.push("    \"created_at\" TIMESTAMPTZ NOT NULL DEFAULT NOW()".into());
        }
        if !has_updated {
            col_defs.push("    \"updated_at\" TIMESTAMPTZ NOT NULL DEFAULT NOW()".into());
        }
    }

    let has_soft_delete_field = model.fields.contains_key("softDelete");
    if model.options.soft_delete
        && !has_soft_delete_field
        && !model.fields.contains_key("deleted_at")
    {
        col_defs.push("    \"deleted_at\" TIMESTAMPTZ".into());
    }

    let mut statements = vec![format!(
        "CREATE TABLE IF NOT EXISTS \"public\".\"{table}\" (\n{}\n);",
        col_defs.join(",\n")
    )];

    // Explicit model-level indexes
    for index in &model.indexes {
        statements.push(create_index_sql(table, index)?);
    }

    // Auto-indexes from fields with `index: true`
    for (field_name, field) in &model.fields {
        if let Some(true) = field_index_flag(field) {
            let auto_idx = IndexAst {
                name: None,
                fields: vec![field_name.clone()],
                unique: false,
                using: IndexMethod::Btree,
            };
            statements.push(create_index_sql(table, &auto_idx)?);
        }
    }

    // Index on deleted_at when softDelete is active (composite field or option)
    let needs_soft_delete_index = has_soft_delete_field
        || (model.options.soft_delete && !model.fields.contains_key("softDelete"));
    if needs_soft_delete_index {
        let idx = IndexAst {
            name: Some(format!("{table}_deleted_at_idx")),
            fields: vec!["deleted_at".into()],
            unique: false,
            using: IndexMethod::Btree,
        };
        statements.push(create_index_sql(table, &idx)?);
    }

    // GIN index for each Blocks field (enables JSONB containment queries).
    for (field_name, field) in &model.fields {
        if let FieldAst::Blocks(b) = field {
            if b.index {
                let gin_idx = IndexAst {
                    name: Some(format!("{table}_{field_name}_gin_idx")),
                    fields: vec![field_name.clone()],
                    unique: false,
                    using: IndexMethod::Gin,
                };
                statements.push(create_index_sql(table, &gin_idx)?);
            }
        }
    }

    // Singleton (global config) — enforce exactly one row via a partial unique index.
    if model.options.singleton {
        statements.push(format!(
            "CREATE UNIQUE INDEX IF NOT EXISTS \"{table}_singleton_idx\" \
             ON \"public\".\"{table}\" ((TRUE));"
        ));
    }

    Ok(statements.join("\n\n"))
}

/// Returns Some(true) if the field has an `index: true` flag, None otherwise.
fn field_index_flag(field: &FieldAst) -> Option<bool> {
    match field {
        FieldAst::Text(f)
        | FieldAst::Email(f)
        | FieldAst::Uuid(f)
        | FieldAst::Integer(f)
        | FieldAst::Float(f)
        | FieldAst::Boolean(f)
        | FieldAst::Datetime(f)
        | FieldAst::BigInt(f)
        | FieldAst::Bytes(f)
        | FieldAst::SmallInt(f)
        | FieldAst::Date(f)
        | FieldAst::Timestamp(f)
        | FieldAst::Serial(f)
        | FieldAst::BigSerial(f)
        | FieldAst::Money(f)
        | FieldAst::Url(f)
        | FieldAst::Ip(f)
        | FieldAst::Cidr(f)
        | FieldAst::Macaddr(f)
        | FieldAst::Interval(f)
        | FieldAst::TsQuery(f)
        | FieldAst::TsVector(f)
        | FieldAst::Xml(f)
        | FieldAst::RichText(f) => {
            if f.index {
                Some(true)
            } else {
                None
            }
        }
        _ => None,
    }
}

// ─── COLUMN DEFINITION ───────────────────────────────────────────────────────

fn field_to_column_def(name: &str, field: &FieldAst) -> Result<String> {
    match field {
        FieldAst::Uuid(f) => Ok(scalar_col(name, "UUID", f)),
        FieldAst::Text(f) | FieldAst::RichText(f) | FieldAst::Bytes(f) => {
            let pg = if matches!(field, FieldAst::RichText(_) | FieldAst::Bytes(_)) {
                if matches!(field, FieldAst::Bytes(_)) {
                    "BYTEA"
                } else {
                    "JSONB"
                }
            } else {
                "TEXT"
            };
            let mut def = scalar_col(name, pg, f);
            if let Some(check) = &f.check {
                def.push_str(&format!(" CHECK ({check})"));
            }
            Ok(def)
        }
        FieldAst::Email(f) => {
            let mut def = scalar_col(name, "TEXT", f);
            def.push_str(&format!(" CHECK (\"{name}\" ~* '^[^@]+@[^@]+\\.[^@]+$')"));
            Ok(def)
        }
        FieldAst::Integer(f) => Ok(scalar_col(name, "INTEGER", f)),
        FieldAst::Float(f) => Ok(scalar_col(name, "DOUBLE PRECISION", f)),
        FieldAst::Boolean(f) => Ok(scalar_col(name, "BOOLEAN", f)),
        FieldAst::Datetime(f) => Ok(scalar_col(name, "TIMESTAMPTZ", f)),
        FieldAst::BigInt(f) => Ok(scalar_col(name, "BIGINT", f)),
        FieldAst::SmallInt(f) => Ok(scalar_col(name, "SMALLINT", f)),
        FieldAst::Date(f) => Ok(scalar_col(name, "DATE", f)),
        FieldAst::Timestamp(f) => Ok(scalar_col(name, "TIMESTAMP", f)),
        FieldAst::Serial(f) => {
            // SERIAL is self-declaring — NOT NULL + sequence default are implicit.
            // primary_key / unique flags still apply.
            let pk = if f.primary_key { " PRIMARY KEY" } else { "" };
            let uniq = if f.unique && !f.primary_key {
                " UNIQUE"
            } else {
                ""
            };
            Ok(format!("\"{name}\" SERIAL{pk}{uniq}"))
        }
        FieldAst::BigSerial(f) => {
            let pk = if f.primary_key { " PRIMARY KEY" } else { "" };
            let uniq = if f.unique && !f.primary_key {
                " UNIQUE"
            } else {
                ""
            };
            Ok(format!("\"{name}\" BIGSERIAL{pk}{uniq}"))
        }
        FieldAst::Money(f) => Ok(scalar_col(name, "NUMERIC(19,4)", f)),
        FieldAst::Url(f) => {
            let mut def = scalar_col(name, "TEXT", f);
            def.push_str(&format!(" CHECK (\"{name}\" ~* '^https?://')"));
            Ok(def)
        }
        FieldAst::Ip(f) => Ok(scalar_col(name, "INET", f)),
        FieldAst::Cidr(f) => Ok(scalar_col(name, "CIDR", f)),
        FieldAst::Macaddr(f) => Ok(scalar_col(name, "MACADDR", f)),
        FieldAst::Interval(f) => Ok(scalar_col(name, "INTERVAL", f)),
        FieldAst::TsQuery(f) => Ok(scalar_col(name, "TSQUERY", f)),
        FieldAst::TsVector(f) => {
            // tsvector is typically NOT NULL; index is GIN.
            let req = if f.required { " NOT NULL" } else { "" };
            Ok(format!("\"{name}\" TSVECTOR{req}"))
        }
        FieldAst::Xml(f) => Ok(scalar_col(name, "XML", f)),
        FieldAst::Array(f) => {
            let req = if f.required { " NOT NULL" } else { "" };
            let uniq = if f.unique { " UNIQUE" } else { "" };
            let elem = f.element_type.to_uppercase();
            Ok(format!("\"{name}\" {elem}[]{req}{uniq}"))
        }
        FieldAst::Slug(f) => {
            let unique = if f.unique { " UNIQUE" } else { "" };
            let req = if f.required { " NOT NULL" } else { "" };
            Ok(format!("\"{name}\" TEXT{req}{unique}"))
        }
        FieldAst::Enum(f) => {
            let vals = f
                .values
                .iter()
                .map(|v| format!("'{v}'"))
                .collect::<Vec<_>>()
                .join(", ");
            let req = if f.required { " NOT NULL" } else { "" };
            let uniq = if f.unique { " UNIQUE" } else { "" };
            let default = f
                .default
                .as_ref()
                .map(|d| format!(" DEFAULT '{d}'"))
                .unwrap_or_default();
            Ok(format!(
                "\"{name}\" TEXT{req}{uniq} CHECK (\"{name}\" IN ({vals})){default}"
            ))
        }
        FieldAst::Json(f) => {
            let req = if f.required { " NOT NULL" } else { "" };
            Ok(format!("\"{name}\" JSONB{req}"))
        }
        FieldAst::Decimal(f) => {
            let pg = match (f.precision, f.scale) {
                (Some(p), Some(s)) => format!("NUMERIC({p}, {s})"),
                (Some(p), None) => format!("NUMERIC({p})"),
                _ => "NUMERIC".into(),
            };
            let req = if f.required { " NOT NULL" } else { "" };
            Ok(format!("\"{name}\" {pg}{req}"))
        }
        FieldAst::Image(f) | FieldAst::File(f) => Ok(scalar_col(
            name,
            "JSONB",
            &ScalarFieldAst {
                pg_type: "JSONB".into(),
                required: f.required,
                ..Default::default()
            },
        )),
        FieldAst::Blocks(f) => Ok(scalar_col(
            name,
            "JSONB",
            &ScalarFieldAst {
                pg_type: "JSONB".into(),
                required: f.required,
                ..Default::default()
            },
        )),
        FieldAst::Geo(f) => {
            let geo_type = f.geo_type.to_uppercase();
            let srid = f.srid.unwrap_or(4326);
            let req = if f.required { " NOT NULL" } else { "" };
            Ok(format!("\"{name}\" GEOGRAPHY({geo_type}, {srid}){req}"))
        }
        FieldAst::Vector(f) => {
            let req = if f.required { " NOT NULL" } else { "" };
            Ok(format!("\"{name}\" vector({}){req}", f.dimensions))
        }
        // Plugin-defined custom field type — use the declared pg_type directly.
        FieldAst::Custom(f) => {
            let req = if f.required { " NOT NULL" } else { "" };
            let uniq = if f.unique { " UNIQUE" } else { "" };
            let default = f
                .default
                .as_ref()
                .map(|d| format!(" DEFAULT {}", render_default(d)))
                .unwrap_or_default();
            Ok(format!(
                "\"{name}\" {pg}{req}{uniq}{default}",
                pg = f.pg_type.to_uppercase()
            ))
        }
        // Composites are expanded at the table level, never called here individually
        FieldAst::Timestamps | FieldAst::Publishable | FieldAst::SoftDelete => {
            anyhow::bail!("composite field '{name}' must be expanded at table level")
        }
        FieldAst::Relation(_) => {
            anyhow::bail!("relation field '{name}' must be handled at table level")
        } // Array is handled above; this arm satisfies exhaustiveness if a new variant slips through
    }
}

fn scalar_col(name: &str, pg_type: &str, f: &ScalarFieldAst) -> String {
    let pk = if f.primary_key { " PRIMARY KEY" } else { "" };
    let req = if f.required && !f.primary_key {
        " NOT NULL"
    } else {
        ""
    };
    let uniq = if f.unique && !f.primary_key {
        " UNIQUE"
    } else {
        ""
    };
    let default = f
        .default
        .as_ref()
        .map(|d| format!(" DEFAULT {}", render_default(d)))
        .unwrap_or_default();
    format!("\"{name}\" {pg_type}{pk}{req}{uniq}{default}")
}

fn render_default(d: &DefaultValueAst) -> String {
    match d {
        DefaultValueAst::Value { value } => match value {
            serde_json::Value::String(s) => format!("'{s}'"),
            serde_json::Value::Bool(b) => b.to_string(),
            other => other.to_string(),
        },
        DefaultValueAst::Expression { expr } => expr.clone(),
        DefaultValueAst::Now => "NOW()".into(),
        DefaultValueAst::GenRandomUuid => "gen_random_uuid()".into(),
    }
}

// ─── ALTER COLUMN ─────────────────────────────────────────────────────────────

fn alter_column_sql(table: &str, column: &str, changes: &serde_json::Value) -> Result<String> {
    let mut stmts: Vec<String> = Vec::new();

    // Type change
    if let Some(type_change) = changes.get("type") {
        let pg_type = type_change
            .get("to_pg")
            .and_then(|v| v.as_str())
            .unwrap_or("TEXT");
        let from_udt = type_change
            .get("from_udt")
            .and_then(|v| v.as_str())
            .unwrap_or("?");

        // Localization-aware USING clause
        let using_expr = if let Some(loc) = changes.get("localization") {
            let direction = loc
                .get("direction")
                .and_then(|v| v.as_str())
                .unwrap_or("add");
            let locale = loc
                .get("default_locale")
                .and_then(|v| v.as_str())
                .unwrap_or("en");
            if direction == "add" {
                // TEXT → JSONB: wrap existing value as default-locale translation
                format!("jsonb_build_object('{locale}', \"{column}\"::text)")
            } else {
                // JSONB → TEXT: extract default-locale value
                format!("(\"{column}\"->>'{}')::text", locale)
            }
        } else {
            format!("\"{column}\"::{pg_type}")
        };

        stmts.push(format!(
            "ALTER TABLE \"public\".\"{table}\" ALTER COLUMN \"{column}\" \
             TYPE {pg_type} USING {using_expr}; \
             -- was: {from_udt}"
        ));
    }

    // Nullability change
    if let Some(null_change) = changes.get("nullability") {
        let to = null_change.get("to").and_then(|v| v.as_str()).unwrap_or("");
        if to == "not_null" {
            // Pre-flight guard: fail if NULLs exist
            stmts.push(format!(
                "DO $$ BEGIN\n  \
                 IF EXISTS (SELECT 1 FROM \"public\".\"{table}\" WHERE \"{column}\" IS NULL) THEN\n    \
                 RAISE EXCEPTION 'Cannot set NOT NULL on {table}.{column}: NULL values exist.';\n  \
                 END IF;\n\
                 END $$;"
            ));
            stmts.push(format!(
                "ALTER TABLE \"public\".\"{table}\" ALTER COLUMN \"{column}\" SET NOT NULL;"
            ));
        } else {
            stmts.push(format!(
                "ALTER TABLE \"public\".\"{table}\" ALTER COLUMN \"{column}\" DROP NOT NULL;"
            ));
        }
    }

    Ok(stmts.join("\n"))
}

// ─── INDEX ───────────────────────────────────────────────────────────────────

fn create_index_sql(table: &str, index: &IndexAst) -> Result<String> {
    let unique = if index.unique { "UNIQUE " } else { "" };
    let method = match &index.using {
        IndexMethod::Btree => "btree",
        IndexMethod::Gin => "gin",
        IndexMethod::Gist => "gist",
        IndexMethod::Hnsw => "hnsw",
        IndexMethod::Brin => "brin",
    };
    let cols = index
        .fields
        .iter()
        .map(|f| format!("\"{f}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let idx_name = index.name.as_deref().unwrap_or_else(|| {
        Box::leak(format!("{table}_{}_idx", index.fields.join("_")).into_boxed_str())
    });

    Ok(format!(
        "CREATE {unique}INDEX IF NOT EXISTS \"{idx_name}\" ON \"public\".\"{table}\" USING {method} ({cols});"
    ))
}

// ─── FOREIGN KEY ─────────────────────────────────────────────────────────────

fn normalize_fk_action(action: &str) -> &'static str {
    match action.to_lowercase().replace([' ', '_', '-'], "").as_str() {
        "cascade" => "CASCADE",
        "setnull" => "SET NULL",
        "setdefault" => "SET DEFAULT",
        "restrict" => "RESTRICT",
        "noaction" => "NO ACTION",
        _ => "RESTRICT",
    }
}

fn add_fk_sql(table: &str, rel: &RelationFieldAst, ref_table: &str) -> Result<String> {
    let fk_col = rel
        .foreign_key
        .as_deref()
        .ok_or_else(|| anyhow::anyhow!("belongsTo relation on '{table}' missing foreignKey"))?;
    let ref_col = rel.references.as_deref().unwrap_or("id");
    let on_delete = normalize_fk_action(rel.on_delete.as_deref().unwrap_or("restrict"));
    let constraint = format!("{table}_{fk_col}_fkey");

    Ok(format!(
        "ALTER TABLE \"public\".\"{table}\" ADD CONSTRAINT \"{constraint}\" \
         FOREIGN KEY (\"{fk_col}\") REFERENCES \"public\".\"{ref_table}\" (\"{ref_col}\") \
         ON DELETE {on_delete} ON UPDATE CASCADE;"
    ))
}

// ─── HELPERS ─────────────────────────────────────────────────────────────────

fn to_snake_case(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(c.to_lowercase().next().unwrap());
    }
    out
}

fn migration_hash(sql: &str) -> String {
    let mut h = Sha256::new();
    h.update(sql.as_bytes());
    format!("sha256:{}", hex::encode(h.finalize()))
}
