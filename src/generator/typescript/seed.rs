//! The TypeScript seed builder, rendered from the language-neutral description.
//!
//! What this file emits is **types plus a manifest**, not an implementation. The runtime
//! that collects operations into an IR is written once, by hand, in `@supatype/cli/seed`;
//! everything generated here is the part that differs per schema. That split is what keeps
//! the six follow-up languages to a renderer each rather than a runtime each, and it is
//! why the generated module is cheap enough to be gitignored and rebuilt on install.
//!
//! **Why the types earn their place.** A seed builder that typed every id as `string` would
//! compile `{ connect: { id: someEvent.id } }` where the column wants an organiser, and the
//! mistake would surface as a foreign-key violation against a fixture. So a reference
//! carries the column it came from in its type, and a `where` accepts only the columns that
//! identify a row. Both are free at runtime: the brand is an optional phantom property, so
//! a literal id still assigns.
//!
//! The one thing this cannot check is itself. The emitted module is asserted here by
//! structure; that it type-checks is proven where it is compiled against the runtime, in
//! the acceptance app.

use crate::generator::seed_model::{
    describe, RelationKind, ScalarKind, SeedColumn, SeedModel, SeedRelation,
};
use crate::parser::ast::{FieldAst, SchemaAst};
use anyhow::Result;

/// The module every generated builder leans on.
const RUNTIME: &str = "@supatype/cli/seed";

/// Render the builder for `ast`.
pub fn generate(ast: &SchemaAst) -> Result<String> {
    let schema = describe(ast);
    // In the order the schema declares them, the same as every other generated file. The AST
    // keeps what `schema/index.ts` says, so a builder read top to bottom reads like the schema
    // it came from.
    let models = schema.models.clone();

    let mut out = String::new();
    out.push_str(&preamble(&schema.fingerprint));

    for model in &models {
        out.push_str(&render_model(model, &models));
    }

    out.push_str(&render_conditions(&models));
    out.push_str(&render_registry(&models));
    out.push_str(&render_manifest(&models));
    Ok(out)
}

// --- The fixed part ---

fn preamble(fingerprint: &str) -> String {
    format!(
        r#"// Generated by supatype-engine. Do not edit manually.
//
// Rebuilt by `supatype generate`, which needs no database and no running stack, so this
// file is gitignored and produced on install rather than committed.

import type {{
  DefaultExpr,
  ModelApi,
  ModelManifest,
  Predicate,
  TimeExpr,
}} from "{RUNTIME}"

// Re-exported so a seed imports its predicates from the same place as its models.
export {{
  and,
  eq,
  gt,
  gte,
  isNull,
  like,
  lt,
  lte,
  neq,
  not,
  notNull,
  oneOf,
  or,
}} from "{RUNTIME}"

/**
 * The schema this builder was generated from.
 *
 * Stamped into every IR the runtime emits, so a seed built against an older schema is
 * refused with the remedy named rather than failing on a column that has since moved.
 */
export const schemaFingerprint = "{fingerprint}"

/**
 * A value tagged with the column it came from.
 *
 * The tag is an optional phantom property, so a plain literal still assigns and only
 * another model's reference does not: `{{ connect: {{ id: someEvent.id }} }}` will not
 * compile where an organiser is wanted.
 */
type Branded<T, M extends string> = T & {{ readonly __supatype?: M }}

/** Anything JSON holds, for the columns that hold it. */
type SeedJson =
  | string
  | number
  | boolean
  | null
  | {{ [key: string]: SeedJson | undefined }}
  | SeedJson[]

/** What `storage.upload()` produces, and the bucket it went to. */
type SeedStorage = {{ bucket: string; path: string }}

/**
 * A Lexical document.
 *
 * Structural rather than imported, so the builder depends on nothing but the runtime. A rich
 * text column also accepts a plain string, which a trigger normalises into one of these on the
 * way in, so prose can be written as prose and a read always returns the document.
 */
type SeedRichText = {{ root: {{ children: unknown[] }} }}

"#
    )
}

// --- Per model ---

fn render_model(model: &SeedModel, all: &[SeedModel]) -> String {
    let name = &model.name;
    let mut out = format!("// --- {name} ---\n\n");

    out.push_str(&render_columns_union(model));
    out.push_str(&render_ref(model));
    out.push_str(&render_where(model));
    out.push_str(&render_create(model, all));
    out
}

/// The columns a predicate may name.
fn render_columns_union(model: &SeedModel) -> String {
    let names: Vec<String> = model.columns.iter().map(|c| json_string(&c.name)).collect();
    let union = if names.is_empty() {
        "never".to_string()
    } else {
        names.join(" | ")
    };
    format!(
        "/** The columns of `{}`, for a condition to name. */\nexport type {}Column = {union}\n\n",
        model.table, model.name
    )
}

/// What an operation hands back, for a later write to point at.
fn render_ref(model: &SeedModel) -> String {
    let mut lines = String::new();
    for column in &model.columns {
        lines.push_str(&format!(
            "  readonly {}: {}\n",
            quote_key(&column.name),
            branded(model, column, &base_type(column))
        ));
    }
    format!(
        "/**\n\
         * A row this seed writes, as something a later write can reference.\n\
         *\n\
         * Not a value read from the database: `alex.id` serialises to\n\
         * `{{\"$ref\": \"alex.id\"}}` and is resolved by the engine, which is why the\n\
         * builder can be pure and ship in every language.\n\
         */\nexport type {}Ref = {{\n{lines}}}\n\n",
        model.name
    )
}

/// The ways one row can be named, which is what an upsert may conflict on.
fn render_where(model: &SeedModel) -> String {
    let name = &model.name;
    if model.unique_keys.is_empty() {
        return format!(
            "/**\n \
             * `{}` has no unique column, so no `where` can name one of its rows.\n \
             *\n \
             * `never` rather than a loose object: an upsert on this model cannot compile a\n \
             * correct `ON CONFLICT` target, and failing at the call is better than guessing.\n \
             */\nexport type {name}Where = never\n\n",
            model.table
        );
    }

    let variants: Vec<String> = model
        .unique_keys
        .iter()
        .map(|key| {
            let fields: Vec<String> = key
                .columns
                .iter()
                .map(|column| match model.column(column) {
                    Some(c) => format!(
                        "{}: {}",
                        quote_key(column),
                        branded(model, c, &base_type(c))
                    ),
                    None => format!("{}: string", quote_key(column)),
                })
                .collect();
            format!("{{ {} }}", fields.join("; "))
        })
        .collect();

    format!(
        "/** Every way to name one `{}` row: its key columns, and nothing else. */\n\
         export type {name}Where =\n  | {}\n\n",
        model.table,
        variants.join("\n  | ")
    )
}

/// What a create or the data half of an upsert accepts.
fn render_create(model: &SeedModel, all: &[SeedModel]) -> String {
    let name = &model.name;
    let mut lines = String::new();

    for column in &model.columns {
        let covered = covered_by_relation(model, column);
        if covered && !column.optional_on_insert {
            lines.push_str("  /** Required: set this, or name the row through its relation. */\n");
        }
        let optional = if column.optional_on_insert || covered {
            "?"
        } else {
            ""
        };
        lines.push_str(&format!(
            "  {}{optional}: {}\n",
            quote_key(&column.name),
            create_type(model, column)
        ));
    }

    for relation in &model.relations {
        if let Some(line) = relation_input(relation, all) {
            lines.push_str(&line);
        }
    }

    format!(
        "/** The values a new `{}` row takes. */\nexport type {name}Create = {{\n{lines}}}\n\n",
        model.table
    )
}

/// Whether a relation on this model can fill this column.
///
/// A required foreign key is still required, but it can be satisfied two ways, and
/// typing it as mandatory would make `{ connect: ... }` on its own impossible to write:
/// the author would have to supply the id they are trying not to hardcode. Marked
/// optional here and enforced by the column's own `NOT NULL`, which the error mapper
/// reports in schema terms rather than as a Postgres code.
fn covered_by_relation(model: &SeedModel, column: &SeedColumn) -> bool {
    model.relations.iter().any(|relation| {
        relation.kind == RelationKind::BelongsTo
            && relation.foreign_key.as_deref() == Some(column.name.as_str())
    })
}

/// One relation's line in a create shape, or nothing when it cannot be written that way.
fn relation_input(relation: &SeedRelation, all: &[SeedModel]) -> Option<String> {
    let field = quote_key(&relation.field);
    let target = &relation.target;

    match relation.kind {
        // This side holds the key, so the row is named rather than created.
        RelationKind::BelongsTo => Some(format!(
            "  /** Point at an existing `{target}`. The foreign key `{}` takes its id. */\n  \
             {field}?: {{ connect: {target}Where }}\n",
            relation.foreign_key.clone().unwrap_or_default()
        )),

        // The junction table has no operation in the IR, so offering this would type-check
        // and then be refused by validation, which is worse than not offering it.
        RelationKind::ManyToMany => Some(format!(
            "  // `{}` is many-to-many: its rows live in a junction table, which a nested\n  \
             // write cannot reach. Write those rows as their own operation.\n",
            relation.field
        )),

        RelationKind::HasOne | RelationKind::HasMany => {
            let nested = nested_create_type(relation, all)?;
            if relation.kind == RelationKind::HasOne {
                Some(format!(
                    "  /** Create the `{target}` this row owns. Its foreign key is filled in. */\n  \
                     {field}?: {{ create: {nested} }}\n"
                ))
            } else {
                Some(format!(
                    "  /** Create the `{target}` rows this row owns. Their foreign keys are filled in. */\n  \
                     {field}?: {{ create: {nested}[] }} | {{ createMany: {nested}[] }}\n"
                ))
            }
        }
    }
}

/// The target's create shape, with the link back to this row removed.
///
/// Removed rather than left optional: the parent supplies it, and an author who set it
/// themselves would be pointing the child at a different row than the one they nested it
/// under. `None` when the pairing is ambiguous, which is the case validation refuses.
fn nested_create_type(relation: &SeedRelation, all: &[SeedModel]) -> Option<String> {
    let key = relation.foreign_key.as_ref()?;
    let back = relation.back_reference.as_ref()?;
    // The target has to exist for its create type to be referable.
    all.iter().find(|m| m.name == relation.target)?;
    Some(format!(
        "Omit<{}Create, {} | {}>",
        relation.target,
        json_string(back),
        json_string(key)
    ))
}

// --- Conditions ---

fn render_conditions(models: &[SeedModel]) -> String {
    if models.is_empty() {
        return "/** No models, so no condition can name one. */\nexport type SupatypeSeedCondition = \
                { environment: string }\n\n"
            .to_string();
    }

    let targets: Vec<String> = models
        .iter()
        .map(|m| format!("ConditionOn<{}, {}Column>", json_string(&m.name), m.name))
        .collect();
    let joined = targets.join("\n  | ");

    format!(
        "// --- Conditions ---\n\n\
         /** A model and the rows of it a condition asks about. */\n\
         type ConditionOn<M extends string, C extends string> = {{\n  \
         model: M\n  \
         /** Omit for \"is this table empty\". */\n  \
         where?: Predicate<C>\n\
         }}\n\n\
         type SeedConditionTarget =\n  | {joined}\n\n\
         /**\n \
          * What `db.$if` takes.\n \
          *\n \
          * Evaluated by the engine at the group's position inside the transaction, because\n \
          * the builder never connects. A condition sees everything ordered before it.\n \
          */\n\
         export type SupatypeSeedCondition =\n  \
         | {{ exists: SeedConditionTarget }}\n  \
         | {{ notExists: SeedConditionTarget }}\n  \
         | {{ environment: string }}\n\n"
    )
}

// --- The registry the runtime reads ---

fn render_registry(models: &[SeedModel]) -> String {
    let mut entries = String::new();
    for model in models {
        entries.push_str(&format!(
            "      {}: ModelApi<{n}Create, {n}Where, {n}Ref>\n",
            quote_key(&model.table),
            n = model.name
        ));
    }

    format!(
        "// --- Registry ---\n\n\
         /**\n \
          * Hands the runtime this schema's shapes.\n \
          *\n \
          * Declared as a module augmentation, the same way the generated client augments\n \
          * `@supatype/client`, so a seed's `db` is typed without importing anything from\n \
          * here: the file is part of the project's program and the augmentation applies.\n \
          */\n\
         declare module \"{RUNTIME}\" {{\n  \
         interface SupatypeSeedRegistry {{\n    \
         models: {{\n{entries}    }}\n    \
         condition: SupatypeSeedCondition\n  \
         }}\n\
         }}\n\n"
    )
}

// --- The runtime manifest ---

/// What the collector needs at runtime, which is less than the types say.
///
/// Only the facts it cannot infer from a value: which columns are exact numerics, so a
/// decimal string is encoded as `{"$numeric": ...}` rather than a bare string; which are
/// temporal, so a `Date` is rendered as an instant; and the relations, so a nested write
/// knows whether it carries one row or many.
fn render_manifest(models: &[SeedModel]) -> String {
    let mut entries = String::new();

    for model in models {
        let numeric = string_list(
            model
                .columns
                .iter()
                .filter(|c| c.kind.is_exact_numeric())
                .map(|c| c.name.as_str()),
        );
        let temporal = string_list(
            model
                .columns
                .iter()
                .filter(|c| c.kind.is_temporal())
                .map(|c| c.name.as_str()),
        );
        let relations: Vec<String> = model
            .relations
            .iter()
            .map(|r| {
                format!(
                    "{}: {{ kind: {}, target: {} }}",
                    quote_key(&r.field),
                    json_string(r.kind.as_str()),
                    json_string(&r.target)
                )
            })
            .collect();

        entries.push_str(&format!(
            "  {}: {{\n    model: {},\n    table: {},\n    numeric: {numeric},\n    \
             temporal: {temporal},\n    relations: {{ {} }},\n  }},\n",
            quote_key(&model.table),
            json_string(&model.name),
            json_string(&model.table),
            relations.join(", ")
        ));
    }

    format!(
        "// --- Manifest ---\n\n\
         /** Read by the runtime while it collects operations. */\n\
         export const seedModels: Record<string, ModelManifest> = {{\n{entries}}}\n"
    )
}

// --- Types ---

/// A column's type with nothing added: no null, no expression, no brand.
fn base_type(column: &SeedColumn) -> String {
    let mut base = match column.kind {
        // The exact kinds. A `number` here is the defect `NUMERIC(19,4)` exists to prevent,
        // so neither of these is ever one.
        ScalarKind::Decimal => "string".to_string(),
        ScalarKind::BigInteger => "bigint | string".to_string(),
        ScalarKind::Integer | ScalarKind::Float => "number".to_string(),
        ScalarKind::Boolean => "boolean".to_string(),
        // Accepting a `Date` as well as an ISO string: a seed that writes epoch integers is
        // not typed in any useful sense, and the runtime renders either as an instant.
        ScalarKind::Timestamp | ScalarKind::Date => "string | Date".to_string(),
        ScalarKind::Enum => enum_union(column),
        ScalarKind::Storage => "SeedStorage".to_string(),
        ScalarKind::Json | ScalarKind::Geo => "SeedJson".to_string(),
        // What the column holds. `SeedJson` accepted any JSON at all, so a seed could put a
        // bare number or an arbitrary object in a rich text column while the database types
        // said it held a document. The prose a trigger turns into one is added by
        // `create_type`, on the way in only.
        ScalarKind::RichText => "SeedRichText".to_string(),
        ScalarKind::Vector => "number[]".to_string(),
        // A field that knows its own shape says so. Without this every JSONB column
        // collapses to an opaque object in the builder, and a `Currency` arrives as
        // something with no `amount` on it.
        ScalarKind::Structured => declared_type(column).unwrap_or_else(|| "SeedJson".to_string()),
        ScalarKind::Text | ScalarKind::Uuid | ScalarKind::Interval | ScalarKind::Binary => {
            "string".to_string()
        }
    };

    if column.array {
        base = format!("({base})[]");
    }
    if column.localized {
        base = format!("{{ [locale: string]: {base} }}");
    }
    base
}

/// A column's type in a create shape: what it holds, plus the ways it can be left to the
/// database.
fn create_type(model: &SeedModel, column: &SeedColumn) -> String {
    let mut parts = vec![branded(model, column, &base_type(column))];
    // Prose, which a trigger normalises into a document on the way in. Only here: a reference
    // resolves from a row that has already been through that trigger, so reading one back is
    // always a document.
    if column.kind == ScalarKind::RichText {
        parts.push("string".to_string());
    }
    if column.nullable {
        parts.push("null".to_string());
    }
    // `expr.now()` and its relatives are typed to the columns that can hold a time, so
    // assigning one to a title does not compile.
    if column.kind.is_temporal() {
        parts.push("TimeExpr".to_string());
    }
    // `expr.default()` is typed to the columns that have one, for the same reason.
    if column.has_default {
        parts.push("DefaultExpr".to_string());
    }
    parts.join(" | ")
}

/// Tag a value with the column it identifies, where that is worth knowing.
///
/// A foreign key is tagged with the column it points at, so a reference to the wrong model
/// does not compile. A unique column is tagged with itself, so a slug cannot be passed
/// where an id is wanted. Everything else is untagged: a name is a name.
fn branded(model: &SeedModel, column: &SeedColumn, base: &str) -> String {
    if let (Some(target), Some(referenced)) = (&column.references, &column.references_column) {
        return format!("Branded<{base}, \"{target}.{referenced}\">");
    }
    let unique = model
        .unique_keys
        .iter()
        .any(|key| key.columns.len() == 1 && key.columns[0] == column.name);
    if unique {
        return format!("Branded<{base}, \"{}.{}\">", model.name, column.name);
    }
    base.to_string()
}

fn enum_union(column: &SeedColumn) -> String {
    if column.enum_values.is_empty() {
        return "string".to_string();
    }
    column
        .enum_values
        .iter()
        .map(|value| json_string(value))
        .collect::<Vec<_>>()
        .join(" | ")
}

// --- Emitting ---

fn string_list<'a>(values: impl Iterator<Item = &'a str>) -> String {
    let items: Vec<String> = values.map(json_string).collect();
    format!("[{}]", items.join(", "))
}

/// A TypeScript string literal, escaped as JSON escapes it.
fn json_string(value: &str) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| format!("\"{value}\""))
}

/// The TypeScript type a field declared for itself, when it declared one.
fn declared_type(column: &SeedColumn) -> Option<String> {
    match column.source.as_ref()? {
        FieldAst::Custom(field) if !field.ts_type.is_empty() => Some(field.ts_type.clone()),
        _ => None,
    }
}

/// An object key, quoted only where it has to be.
///
/// A table named `order-items` is a legal identifier in Postgres and not one in
/// TypeScript, so the generated file would not parse if every key were emitted bare.
fn quote_key(key: &str) -> String {
    let valid = !key.is_empty()
        && key
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && key
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if valid {
        key.to_string()
    } else {
        json_string(key)
    }
}

