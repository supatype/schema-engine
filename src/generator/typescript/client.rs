use crate::parser::ast::SchemaAst;
use anyhow::Result;

/// DEPRECATED — not wired into `generate` / CLI.
/// Product F11 lives on `@supatype/client` as `client.from(table).subscribe(...)`
/// against the WAL realtime service. Do not revive this NOTIFY-based prototype.
///
/// Generate a typed TypeScript client module for every model in the schema.
///
/// Each model gets a class with:
///   - CRUD helpers delegating to the PostgREST endpoint.
///   - A `subscribe(callback)` method that opens a WebSocket to the realtime
///     server and listens on the `supatype_{table}` pg_notify channel.
///     It returns an unsubscribe function (`() => void`) that closes the socket.
pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out =
        String::from("// Generated by supatype-engine — do not edit manually.\n// @ts-nocheck\n\n");

    // Preamble: RealtimeEvent type shared by all model clients.
    out.push_str(
        r#"export interface RealtimeEvent {
  table: string;
  event: "INSERT" | "UPDATE" | "DELETE";
  id: unknown;
}

"#,
    );

    for model in &ast.models {
        let class_name = pascal_case(&model.name);
        let table = &model.table_name();

        out.push_str(&format!(
            r#"export class {class_name}Client {{
  constructor(private readonly baseUrl: string, private readonly headers: Record<string, string> = {{}}) {{}}

  subscribe(
    callback: (event: RealtimeEvent) => void
  ): () => void {{
    const ws = new WebSocket(`${{this.baseUrl.replace(/^http/, "ws")}}/realtime/v1/`)
    ws.onopen = () => {{
      ws.send(JSON.stringify({{ type: "subscribe", channel: "supatype_{table}" }}))
    }}
    ws.onmessage = (e) => {{
      try {{ callback(JSON.parse(e.data as string) as RealtimeEvent) }}
      catch {{ /* ignore parse errors */ }}
    }}
    return () => ws.close()
  }}
}}

"#
        ));
    }

    Ok(out)
}

/// Convert a snake_case or camelCase identifier to PascalCase for use as a
/// TypeScript class name, e.g. "blog_post" → "BlogPost", "post" → "Post".
fn pascal_case(s: &str) -> String {
    s.split(['_', '-'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}
