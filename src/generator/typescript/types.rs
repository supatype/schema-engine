use crate::parser::ast::{FieldAst, ModelAst, RelationCardinality, SchemaAst};
use crate::parser::resolver::to_snake_case;
use anyhow::Result;

/// True if a field is (or contains) a RichText field — used to emit the RichText type alias.
fn field_is_richtext(field: &FieldAst) -> bool {
    match field {
        FieldAst::RichText(_) => true,
        FieldAst::Blocks(b) => b
            .blocks
            .iter()
            .any(|bl| bl.fields.iter().any(|(_, bf)| field_is_richtext(bf))),
        _ => false,
    }
}

pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out = String::from("// Generated by supatype-engine. Do not edit manually.\n\n");
    emit_shared_types(ast, &mut out);

    out.push_str("export type Database = {\n  public: {\n    Tables: {\n");

    for model in &ast.models {
        emit_table(model, &mut out);
    }

    out.push_str("    }\n");
    out.push_str("    Views: {\n      [_ in never]: never\n    }\n");
    out.push_str("    Functions: {\n      [_ in never]: never\n    }\n");
    out.push_str("    Enums: {\n      [_ in never]: never\n    }\n");
    out.push_str("    CompositeTypes: {\n      [_ in never]: never\n    }\n");
    out.push_str("  }\n}\n");

    Ok(out)
}

/// The type aliases a generated file needs before it can name a column's type.
///
/// Emitted only where the schema uses them, and shared with the client augmentation so the
/// two generated files cannot disagree about what a localized column or a stored file is.
pub(crate) fn emit_shared_types(ast: &SchemaAst, out: &mut String) {
    let has_storage = ast.models.iter().any(|m| {
        m.fields
            .values()
            .any(|f| matches!(f, FieldAst::Image(_) | FieldAst::File(_)))
    });

    // A localized column is jsonb holding {"en": ..., "fr": ...}. Typing it as the bare value
    // invited `.toUpperCase()` on an object, which compiled and then failed in the browser.
    let has_localized = ast.models.iter().any(|m| {
        m.fields
            .values()
            .any(crate::parser::accessors::is_localized)
    });

    let has_richtext = ast
        .models
        .iter()
        .any(|m| m.fields.values().any(field_is_richtext));

    let has_button = ast
        .models
        .iter()
        .any(|m| m.fields.values().any(|f| matches!(f, FieldAst::Button(_))));

    // RichText columns store a Lexical document; type them as SerializedEditorState
    // rather than generic Json so editors/clients get the real shape.
    if has_richtext {
        out.push_str("import type { SerializedEditorState } from \"@supatype/types/lexical\"\n\n");
    }

    out.push_str(
        "export type Json =\n  \
         | string\n  \
         | number\n  \
         | boolean\n  \
         | null\n  \
         | { [key: string]: Json | undefined }\n  \
         | Json[]\n\n",
    );

    if has_richtext {
        out.push_str("export type RichText = SerializedEditorState\n\n");
    }

    if has_button {
        out.push_str(
            "export type ButtonTarget = \"_self\" | \"_blank\"\n\n\
             export type Button = {\n  \
             label: string\n  \
             href: string\n  \
             ariaLabel?: string\n  \
             target?: ButtonTarget\n\
             }\n\n",
        );
    }

    if has_localized {
        out.push_str("export type LocalizedValue<T> = { [locale: string]: T }\n\n");
    }

    if has_storage {
        out.push_str(
            "export type StorageReference = {\n  \
             bucket: string\n  \
             path: string\n\
             }\n\n",
        );
    }
}

// ─── Per-table emitter ───────────────────────────────────────────────────────

fn emit_table(model: &ModelAst, out: &mut String) {
    let table = &model.table_name();
    out.push_str(&format!("      {table}: {{\n"));

    out.push_str("        Row: {\n");
    emit_fields(model, Mode::Row, out, "          ");
    out.push_str("        }\n");

    out.push_str("        Insert: {\n");
    emit_fields(model, Mode::Insert, out, "          ");
    out.push_str("        }\n");

    out.push_str("        Update: {\n");
    emit_fields(model, Mode::Update, out, "          ");
    out.push_str("        }\n");

    out.push_str("        Relationships: []\n");
    out.push_str("      }\n");
}

// ─── Field emission ──────────────────────────────────────────────────────────

#[derive(Clone, Copy, PartialEq)]
pub(crate) enum Mode {
    Row,
    Insert,
    Update,
}

/// One object body: every column of `model`, in `mode`, indented by `ind`.
pub(crate) fn emit_fields(model: &ModelAst, mode: Mode, out: &mut String, ind: &str) {
    for (name, field) in &model.fields {
        match field {
            FieldAst::Relation(rel) => {
                // belongsTo relations create a UUID FK column on this table (e.g. authUser →
                // auth_user_id). hasMany/hasOne/manyToMany keep the FK on the other side or on a
                // junction table, so emit nothing here.
                //
                // Nullability follows `rel.required`, which is the same field the differ reads to
                // decide NOT NULL. It was hardcoded nullable here, so every
                // `RelatedTo<X, { required: true }>` produced `x_id: string | null` over a column
                // that rejects null: the generated type contradicted the schema it was generated
                // from, and said the safer-looking thing while being the wrong one.
                if matches!(rel.cardinality, RelationCardinality::BelongsTo) {
                    let fk_col = rel
                        .foreign_key
                        .clone()
                        .unwrap_or_else(|| format!("{}_id", to_snake_case(name)));
                    // When the FK column is also declared explicitly as a scalar
                    // field (the `author: RelatedTo<…>` + `author_id` pattern),
                    // that scalar definition is emitted by the `other` branch.
                    // Emitting it here too would produce a duplicate key in the
                    // generated Row/Insert/Update object types.
                    let explicitly_declared = model
                        .fields
                        .get(fk_col.as_str())
                        .map(|f| !matches!(f, FieldAst::Relation(_)))
                        .unwrap_or(false);
                    if !explicitly_declared {
                        emit_one(&fk_col, "string", !rel.required, false, mode, out, ind);
                    }
                }
            }
            FieldAst::Timestamps => emit_timestamps(mode, out, ind, true, true),
            FieldAst::Publishable => emit_publishable(mode, out, ind),
            FieldAst::SoftDelete => emit_soft_delete(mode, out, ind),
            other => {
                let (ts, nullable) = ts_type_of(other);
                // Widen before wrapping, not after. A localized column holds one value per
                // locale and the trigger normalises each of them, so prose is accepted per
                // locale: `LocalizedValue<RichText | string>`. Widening the wrapper instead
                // says a bare string is a valid write to the column, which the trigger then
                // stores as a single document where a locale map belongs.
                let ts = widen_for_writes(other, &ts, mode);
                let ts = if crate::parser::accessors::is_localized(other) {
                    format!("LocalizedValue<{ts}>")
                } else {
                    ts
                };
                // What Postgres refuses to write (a generated column, a `GENERATED ALWAYS`
                // identity) can be neither inserted nor updated: `never`, as an optional key so a
                // row read back can still be spread into a write.
                if mode != Mode::Row && crate::parser::accessors::never_written(other) {
                    out.push_str(&format!("{ind}{name}?: never\n"));
                    continue;
                }
                let has_def =
                    field_has_default(other) || crate::parser::accessors::database_fills(other);
                emit_one(name, &ts, nullable, has_def, mode, out, ind);
            }
        }
    }

    if model.options.timestamps && !model.fields.contains_key("timestamps") {
        let has_ca =
            model.fields.contains_key("created_at") || model.fields.contains_key("createdAt");
        let has_ua =
            model.fields.contains_key("updated_at") || model.fields.contains_key("updatedAt");
        if !has_ca || !has_ua {
            emit_timestamps(mode, out, ind, !has_ca, !has_ua);
        }
    }

    if model.options.soft_delete
        && !model.fields.contains_key("softDelete")
        && !model.fields.contains_key("deleted_at")
        && !model.fields.contains_key("deletedAt")
    {
        emit_soft_delete(mode, out, ind);
    }
}

fn emit_one(
    name: &str,
    ts: &str,
    nullable: bool,
    has_default: bool,
    mode: Mode,
    out: &mut String,
    ind: &str,
) {
    let (opt, suffix) = match mode {
        Mode::Row => {
            if nullable {
                ("", " | null")
            } else {
                ("", "")
            }
        }
        Mode::Insert => {
            if has_default || nullable {
                if nullable {
                    ("?", " | null")
                } else {
                    ("?", "")
                }
            } else {
                ("", "")
            }
        }
        Mode::Update => {
            if nullable {
                ("?", " | null")
            } else {
                ("?", "")
            }
        }
    };
    out.push_str(&format!("{ind}{name}{opt}: {ts}{suffix}\n"));
}

// ─── Composite expansions ────────────────────────────────────────────────────

/// What a column accepts on the way in, where that is wider than what it returns.
///
/// A rich text column holds a Lexical document, and a trigger normalises a plain string into
/// one on insert and update, so writing prose is a string and reading it is always a document.
/// This is the only place the three modes differ by more than optionality, and flattening them
/// back would either demand hand-built Lexical JSON from every caller or claim a read might
/// return a string, which after the trigger it cannot.
fn widen_for_writes(field: &FieldAst, ts: &str, mode: Mode) -> String {
    if mode == Mode::Row || !matches!(field, FieldAst::RichText(_)) {
        return ts.to_string();
    }
    format!("{ts} | string")
}

fn emit_timestamps(mode: Mode, out: &mut String, ind: &str, ca: bool, ua: bool) {
    let opt = if mode == Mode::Row { "" } else { "?" };
    if ca {
        out.push_str(&format!("{ind}created_at{opt}: string\n"));
    }
    if ua {
        out.push_str(&format!("{ind}updated_at{opt}: string\n"));
    }
}

fn emit_publishable(mode: Mode, out: &mut String, ind: &str) {
    let st = r#""draft" | "published" | "scheduled" | "archived""#;
    let opt = if mode == Mode::Row { "" } else { "?" };
    out.push_str(&format!("{ind}status{opt}: {st}\n"));
    out.push_str(&format!("{ind}published_at{opt}: string | null\n"));
    out.push_str(&format!("{ind}scheduled_at{opt}: string | null\n"));
}

fn emit_soft_delete(mode: Mode, out: &mut String, ind: &str) {
    let opt = if mode == Mode::Row { "" } else { "?" };
    out.push_str(&format!("{ind}deleted_at{opt}: string | null\n"));
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

fn field_has_default(field: &FieldAst) -> bool {
    match field {
        FieldAst::Text(f)
        | FieldAst::Color(f)
        | FieldAst::Email(f)
        | FieldAst::Url(f)
        | FieldAst::Ip(f)
        | FieldAst::Cidr(f)
        | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f)
        | FieldAst::Xml(f)
        | FieldAst::RichText(f)
        | FieldAst::Integer(f)
        | FieldAst::Float(f)
        | FieldAst::BigInt(f)
        | FieldAst::Boolean(f)
        | FieldAst::Datetime(f)
        | FieldAst::Uuid(f)
        | FieldAst::SmallInt(f)
        | FieldAst::Date(f)
        | FieldAst::Timestamp(f)
        | FieldAst::Interval(f)
        | FieldAst::TsQuery(f)
        | FieldAst::TsVector(f)
        | FieldAst::Money(f) => f.default.is_some(),
        FieldAst::Serial(_) | FieldAst::BigSerial(_) => true,
        FieldAst::Slug(_) => true,
        FieldAst::Enum(f) => f.default.is_some(),
        FieldAst::Custom(f) => f.default.is_some(),
        FieldAst::Array(f) => f.default.is_some(),
        _ => false,
    }
}

fn ts_type_of(field: &FieldAst) -> (String, bool) {
    match field {
        FieldAst::Text(f)
        | FieldAst::Color(f)
        | FieldAst::Email(f)
        | FieldAst::Url(f)
        | FieldAst::Ip(f)
        | FieldAst::Cidr(f)
        | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f)
        | FieldAst::Xml(f) => ("string".into(), !f.required),
        FieldAst::RichText(f) => ("RichText".into(), !f.required),
        FieldAst::Integer(f) | FieldAst::Float(f) | FieldAst::SmallInt(f) | FieldAst::Serial(f) => {
            ("number".into(), !f.required)
        }
        // The exact-value kinds. Each names a value no binary float holds, so the type
        // `@supatype/types` declares for it is the one that survives the wire: `bigint` for
        // BIGINT, and an exact decimal string for the two NUMERIC kinds. Money sat in the arm
        // above, which is how a currency amount reached callers as an IEEE-754 double.
        // Separate arms because Decimal carries precision and scale, so the inner types differ.
        FieldAst::BigInt(f) | FieldAst::BigSerial(f) => ("bigint".into(), !f.required),
        FieldAst::Money(f) => ("string".into(), !f.required),
        FieldAst::Decimal(f) => ("string".into(), !f.required),
        FieldAst::Boolean(f) => ("boolean".into(), !f.required),
        FieldAst::Datetime(f)
        | FieldAst::Date(f)
        | FieldAst::Timestamp(f)
        | FieldAst::Uuid(f)
        | FieldAst::Interval(f) => ("string".into(), !f.required),
        FieldAst::Slug(f) => ("string".into(), !f.required),
        FieldAst::TsQuery(f) | FieldAst::TsVector(f) => ("string".into(), !f.required),
        FieldAst::Enum(f) => {
            let union = f
                .values
                .iter()
                .map(|v| format!("\"{v}\""))
                .collect::<Vec<_>>()
                .join(" | ");
            (union, !f.required)
        }
        FieldAst::Json(f) => ("Json".into(), !f.required),
        FieldAst::Button(f) => ("Button".into(), !f.required),
        FieldAst::Array(f) => {
            let elem = match f.element_type.to_lowercase().as_str() {
                "integer" | "int4" | "int" | "smallint" | "int2" | "bigint" | "int8" | "float"
                | "double precision" | "float8" | "real" | "float4" | "numeric" => "number",
                "boolean" | "bool" => "boolean",
                _ => "string",
            };
            (format!("{elem}[]"), !f.required)
        }
        FieldAst::Image(f) | FieldAst::File(f) => ("StorageReference".into(), !f.required),
        FieldAst::Geo(f) => ("Json".into(), !f.required),
        FieldAst::Vector(f) => (format!("number[] /* dim {} */", f.dimensions), !f.required),
        FieldAst::Blocks(f) => {
            if f.blocks.is_empty() {
                ("Json[]".into(), !f.required)
            } else {
                let variants: Vec<String> = f
                    .blocks
                    .iter()
                    .map(|b| {
                        let defs: Vec<String> = b
                            .fields
                            .iter()
                            .filter(|(_, bf)| !matches!(bf, FieldAst::Relation(_)))
                            .map(|(fname, bf)| {
                                let (ts, nullable) = ts_type_of(bf);
                                let opt = if nullable { "?" } else { "" };
                                format!("{fname}{opt}: {ts}")
                            })
                            .collect();
                        format!(
                            "{{ type: \"{}\"; data: {{ {} }} }}",
                            b.name,
                            defs.join("; ")
                        )
                    })
                    .collect();
                let union = variants.join(" | ");
                (format!("({union})[]"), !f.required)
            }
        }
        FieldAst::Custom(f) => (f.ts_type.clone(), !f.required),
        FieldAst::Timestamps | FieldAst::Publishable | FieldAst::SoftDelete => {
            ("never".into(), false)
        }
        FieldAst::Relation(_) => ("never".into(), false),
    }
}
