use anyhow::Result;
use crate::parser::ast::{FieldAst, SchemaAst};

pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out = String::from("// Generated by supatype-engine — do not edit manually.\n// @ts-nocheck\n\n");

    for model in &ast.models {
        // Row type (all fields, nullability from schema)
        out.push_str(&format!("export interface {}Row {{\n", model.name));
        for (name, field) in &model.fields {
            if matches!(field, FieldAst::Relation(_)) { continue; }
            let (ts_type, nullable) = ts_type_of(field);
            let opt = if nullable { "?" } else { "" };
            out.push_str(&format!("  {name}{opt}: {ts_type};\n"));
        }
        out.push_str("}\n\n");

        // Insert type (nullable fields become optional, serial fields omitted)
        out.push_str(&format!("export interface {}Insert {{\n", model.name));
        for (name, field) in &model.fields {
            if matches!(field, FieldAst::Relation(_)
                | FieldAst::Timestamps
                | FieldAst::SoftDelete) { continue; }
            if matches!(field, FieldAst::Publishable) { continue; }
            let (ts_type, nullable) = ts_type_of(field);
            let opt = if nullable { "?" } else { "" };
            out.push_str(&format!("  {name}{opt}: {ts_type};\n"));
        }
        out.push_str("}\n\n");
    }

    Ok(out)
}

fn ts_type_of(field: &FieldAst) -> (String, bool) {
    match field {
        FieldAst::Text(f) | FieldAst::Email(f) | FieldAst::Url(f)
        | FieldAst::Ip(f) | FieldAst::Cidr(f) | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f) | FieldAst::Xml(f) => ("string".into(), !f.required),
        FieldAst::RichText(f) => ("Record<string, unknown>".into(), !f.required),
        FieldAst::Integer(f) | FieldAst::Float(f) | FieldAst::SmallInt(f)
        | FieldAst::Serial(f) | FieldAst::Money(f) => ("number".into(), !f.required),
        FieldAst::BigInt(f) | FieldAst::BigSerial(f) => {
            ("string".into(), !f.required) // large ints as string for JSON safety
        }
        FieldAst::Decimal(f) => ("string".into(), !f.required),
        FieldAst::Boolean(f) => ("boolean".into(), !f.required),
        FieldAst::Datetime(f) | FieldAst::Date(f) | FieldAst::Timestamp(f)
        | FieldAst::Uuid(f) | FieldAst::Interval(f) => ("string".into(), !f.required),
        FieldAst::Slug(f) => ("string".into(), !f.required),
        FieldAst::TsQuery(f) | FieldAst::TsVector(f) => ("string".into(), !f.required),
        FieldAst::Enum(f) => {
            let union = f.values.iter().map(|v| format!("\"{v}\"")).collect::<Vec<_>>().join(" | ");
            (union, !f.required)
        }
        FieldAst::Json(f) => ("unknown".into(), !f.required),
        FieldAst::Array(f) => {
            let elem = match f.element_type.to_lowercase().as_str() {
                "integer" | "int4" | "int" | "smallint" | "int2"
                | "bigint" | "int8" | "float" | "double precision" | "float8"
                | "real" | "float4" | "numeric" => "number",
                "boolean" | "bool" => "boolean",
                _ => "string",
            };
            (format!("{elem}[]"), !f.required)
        }
        FieldAst::Image(f) | FieldAst::File(f) => ("StorageReference".into(), !f.required),
        FieldAst::Geo(f) => ("GeoJSON.Geometry".into(), !f.required),
        FieldAst::Vector(f) => (format!("number[] /* vector({}) */", f.dimensions), !f.required),
        FieldAst::Blocks(f) => {
            // Discriminated union: Array<{ type: "hero"; data: { ... } } | { type: "text"; ... }>
            if f.blocks.is_empty() {
                (
                    "Array<{ type: string; data: Record<string, unknown> }>".into(),
                    !f.required,
                )
            } else {
                let variants: Vec<String> = f.blocks.iter().map(|b| {
                    let field_defs: Vec<String> = b.fields.iter()
                        .filter(|(_, f)| !matches!(f, FieldAst::Relation(_)))
                        .map(|(fname, ffield)| {
                            let (ts_type, nullable) = ts_type_of(ffield);
                            let opt = if nullable { "?" } else { "" };
                            format!("{fname}{opt}: {ts_type}")
                        })
                        .collect();
                    let data_fields = field_defs.join("; ");
                    format!("{{ type: \"{}\"; data: {{ {} }} }}", b.name, data_fields)
                }).collect();
                let union = variants.join(" | ");
                (format!("Array<{union}>"), !f.required)
            }
        }
        FieldAst::Custom(f) => (f.ts_type.clone(), !f.required),
        FieldAst::Timestamps => ("never".into(), false), // expanded inline
        FieldAst::Publishable => ("never".into(), false),
        FieldAst::SoftDelete => ("never".into(), false),
        FieldAst::Relation(_) => ("never".into(), false),
    }
}
