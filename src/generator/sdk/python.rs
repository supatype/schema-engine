use crate::parser::ast::{FieldAst, SchemaAst};
use anyhow::Result;

pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out = String::new();
    out.push_str("# Generated by supatype-engine — do not edit manually.\n");
    out.push_str("# Requires Python 3.10+\n\n");
    out.push_str("from __future__ import annotations\n");
    out.push_str("from dataclasses import dataclass\n");
    out.push_str("from datetime import datetime, date\n");
    out.push_str("from decimal import Decimal\n");
    out.push_str("from typing import Any, Literal, Optional\n\n");

    for model in &ast.models {
        // Emit Literal aliases for enum fields
        for (fname, f) in &model.fields {
            if let FieldAst::Enum(e) = f {
                let type_name = enum_type_name(&model.name, fname);
                let variants = e
                    .values
                    .iter()
                    .map(|v| format!("\"{}\"", v))
                    .collect::<Vec<_>>()
                    .join(", ");
                out.push_str(&format!("{} = Literal[{}]\n", type_name, variants));
            }
        }

        out.push_str("\n\n@dataclass\n");
        out.push_str(&format!("class {}:\n", model.name));

        // Collect scalar fields — split required vs optional so @dataclass ordering is valid:
        // Python requires fields without defaults to precede fields with defaults.
        let mut required_lines: Vec<String> = Vec::new();
        let mut optional_lines: Vec<String> = Vec::new();

        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let (py_type, nullable) = py_type_of(&model.name, name, fld);
            if nullable {
                optional_lines.push(format!("    {}: Optional[{}] = None\n", name, py_type));
            } else {
                required_lines.push(format!("    {}: {}\n", name, py_type));
            }
        }

        // Composite expansions always have defaults so they go in optional_lines
        for fld in model.fields.values() {
            match fld {
                FieldAst::Timestamps => {
                    optional_lines.push("    created_at: Optional[datetime] = None\n".into());
                    optional_lines.push("    updated_at: Optional[datetime] = None\n".into());
                }
                FieldAst::Publishable => {
                    optional_lines.push("    status: Optional[Literal[\"draft\", \"published\", \"scheduled\", \"archived\"]] = None\n".into());
                    optional_lines.push("    published_at: Optional[datetime] = None\n".into());
                    optional_lines.push("    scheduled_at: Optional[datetime] = None\n".into());
                }
                FieldAst::SoftDelete => {
                    optional_lines.push("    deleted_at: Optional[datetime] = None\n".into());
                }
                _ => {}
            }
        }

        let wrote_field = !required_lines.is_empty() || !optional_lines.is_empty();
        for line in required_lines.iter().chain(optional_lines.iter()) {
            out.push_str(line);
        }
        if !wrote_field {
            out.push_str("    pass\n");
        }

        out.push('\n');
    }

    Ok(out)
}

fn enum_type_name(model: &str, field: &str) -> String {
    let cap = field
        .chars()
        .next()
        .map(|c| c.to_uppercase().to_string())
        .unwrap_or_default();
    let rest = &field[field
        .char_indices()
        .nth(1)
        .map(|(i, _)| i)
        .unwrap_or(field.len())..];
    format!("{}{}Enum", model, cap + rest)
}

fn py_type_of(model: &str, name: &str, field: &FieldAst) -> (String, bool) {
    match field {
        FieldAst::Text(f)
        | FieldAst::Email(f)
        | FieldAst::Url(f)
        | FieldAst::Ip(f)
        | FieldAst::Cidr(f)
        | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f)
        | FieldAst::Xml(f)
        | FieldAst::TsQuery(f)
        | FieldAst::TsVector(f)
        | FieldAst::Interval(f)
        | FieldAst::Uuid(f) => ("str".into(), !f.required),
        FieldAst::Slug(f) => ("str".into(), !f.required),
        FieldAst::Integer(f) | FieldAst::SmallInt(f) | FieldAst::Serial(f) => {
            ("int".into(), !f.required)
        }
        FieldAst::Float(f) | FieldAst::Money(f) => ("float".into(), !f.required),
        FieldAst::BigInt(f) | FieldAst::BigSerial(f) => ("int".into(), !f.required),
        FieldAst::Decimal(f) => ("Decimal".into(), !f.required),
        FieldAst::Boolean(f) => ("bool".into(), !f.required),
        FieldAst::Datetime(f) | FieldAst::Timestamp(f) => ("datetime".into(), !f.required),
        FieldAst::Date(f) => ("date".into(), !f.required),
        FieldAst::Enum(e) => (enum_type_name(model, name), !e.required),
        FieldAst::Json(_) => ("Any".into(), true),
        FieldAst::Array(a) => {
            let elem = py_array_elem(&a.element_type);
            (format!("list[{}]", elem), !a.required)
        }
        FieldAst::Image(f) | FieldAst::File(f) => ("dict[str, Any]".into(), !f.required),
        FieldAst::Geo(f) => ("dict[str, Any]".into(), !f.required),
        FieldAst::Vector(f) => ("list[float]".into(), !f.required),
        FieldAst::Blocks(f) => ("list[dict[str, Any]]".into(), !f.required),
        FieldAst::Custom(f) => (ts_to_python(&f.ts_type), !f.required),
        _ => ("Any".into(), true),
    }
}

fn py_array_elem(element_type: &str) -> &'static str {
    match element_type.to_uppercase().as_str() {
        "INTEGER" | "INT" | "INT4" | "SMALLINT" | "BIGINT" => "int",
        "FLOAT" | "FLOAT8" | "NUMERIC" | "DECIMAL" | "REAL" => "float",
        "BOOLEAN" | "BOOL" => "bool",
        _ => "str",
    }
}

fn ts_to_python(ts: &str) -> String {
    match ts {
        "string" => "str".into(),
        "number" => "float".into(),
        "boolean" => "bool".into(),
        _ => "Any".into(),
    }
}
