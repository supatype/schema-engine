use crate::parser::ast::{FieldAst, SchemaAst};
use anyhow::Result;

pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out = String::new();
    out.push_str("// Generated by supatype-engine. Do not edit manually.\n\n");

    for model in &ast.models {
        out.push_str(&format!("class {} {{\n", model.name));

        // Fields
        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let (dart_type, nullable) = dart_type_of(fld);
            let prop_name = camel_case(name);
            if nullable {
                out.push_str(&format!("  final {}? {};\n", dart_type, prop_name));
            } else {
                out.push_str(&format!("  final {} {};\n", dart_type, prop_name));
            }
        }

        // Composite expansions
        for fld in model.fields.values() {
            match fld {
                FieldAst::Timestamps => {
                    out.push_str("  final DateTime? createdAt;\n");
                    out.push_str("  final DateTime? updatedAt;\n");
                }
                FieldAst::Publishable => {
                    out.push_str("  final String? status;\n");
                    out.push_str("  final DateTime? publishedAt;\n");
                    out.push_str("  final DateTime? scheduledAt;\n");
                }
                FieldAst::SoftDelete => {
                    out.push_str("  final DateTime? deletedAt;\n");
                }
                _ => {}
            }
        }

        // Constructor
        out.push_str(&format!("\n  const {}({{\n", model.name));
        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let prop_name = camel_case(name);
            out.push_str(&format!("    required this.{},\n", prop_name));
        }
        for fld in model.fields.values() {
            match fld {
                FieldAst::Timestamps => {
                    out.push_str("    this.createdAt,\n");
                    out.push_str("    this.updatedAt,\n");
                }
                FieldAst::Publishable => {
                    out.push_str("    this.status,\n");
                    out.push_str("    this.publishedAt,\n");
                    out.push_str("    this.scheduledAt,\n");
                }
                FieldAst::SoftDelete => {
                    out.push_str("    this.deletedAt,\n");
                }
                _ => {}
            }
        }
        out.push_str("  });\n");

        // fromJson factory
        out.push_str(&format!(
            "\n  factory {}.fromJson(Map<String, dynamic> json) {{\n",
            model.name
        ));
        out.push_str(&format!("    return {}(\n", model.name));
        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let prop_name = camel_case(name);
            let from = dart_from_json(name, fld);
            out.push_str(&format!("      {}: {},\n", prop_name, from));
        }
        for fld in model.fields.values() {
            match fld {
                FieldAst::Timestamps => {
                    out.push_str("      createdAt: json['created_at'] != null ? DateTime.parse(json['created_at']) : null,\n");
                    out.push_str("      updatedAt: json['updated_at'] != null ? DateTime.parse(json['updated_at']) : null,\n");
                }
                FieldAst::Publishable => {
                    out.push_str("      status: json['status'] as String?,\n");
                    out.push_str("      publishedAt: json['published_at'] != null ? DateTime.parse(json['published_at']) : null,\n");
                    out.push_str("      scheduledAt: json['scheduled_at'] != null ? DateTime.parse(json['scheduled_at']) : null,\n");
                }
                FieldAst::SoftDelete => {
                    out.push_str("      deletedAt: json['deleted_at'] != null ? DateTime.parse(json['deleted_at']) : null,\n");
                }
                _ => {}
            }
        }
        out.push_str("    );\n");
        out.push_str("  }\n");

        // toJson
        out.push_str("\n  Map<String, dynamic> toJson() => {\n");
        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let prop_name = camel_case(name);
            let to = dart_to_json(&prop_name, fld);
            out.push_str(&format!("        '{}': {},\n", name, to));
        }
        out.push_str("      };\n");

        out.push_str("}\n\n");
    }

    Ok(out)
}

fn dart_type_of(field: &FieldAst) -> (String, bool) {
    match field {
        FieldAst::Text(f)
        | FieldAst::Email(f)
        | FieldAst::Url(f)
        | FieldAst::Ip(f)
        | FieldAst::Cidr(f)
        | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f)
        | FieldAst::Xml(f)
        | FieldAst::TsQuery(f)
        | FieldAst::TsVector(f)
        | FieldAst::Interval(f)
        | FieldAst::Uuid(f) => ("String".into(), !f.required),
        FieldAst::Slug(f) => ("String".into(), !f.required),
        FieldAst::Integer(f) | FieldAst::SmallInt(f) | FieldAst::Serial(f) => {
            ("int".into(), !f.required)
        }
        FieldAst::Float(f) => ("double".into(), !f.required),
        FieldAst::BigInt(f) | FieldAst::BigSerial(f) => ("int".into(), !f.required),
        // money and decimal are both NUMERIC. Exact digits, which no binary float holds, and
        // Dart has no built-in exact decimal, so the digits cross as a String.
        FieldAst::Money(f) => ("String".into(), !f.required),
        FieldAst::Decimal(f) => ("String".into(), !f.required),
        FieldAst::Boolean(f) => ("bool".into(), !f.required),
        FieldAst::Datetime(f) | FieldAst::Timestamp(f) | FieldAst::Date(f) => {
            ("DateTime".into(), !f.required)
        }
        FieldAst::Enum(e) => ("String".into(), !e.required),
        FieldAst::Json(_) => ("Map<String, dynamic>".into(), true),
        FieldAst::Array(a) => {
            let elem = dart_array_elem(&a.element_type);
            (format!("List<{}>", elem), !a.required)
        }
        FieldAst::Image(f) | FieldAst::File(f) => ("Map<String, dynamic>".into(), !f.required),
        FieldAst::Geo(f) => ("Map<String, dynamic>".into(), !f.required),
        FieldAst::Vector(f) => ("List<double>".into(), !f.required),
        FieldAst::Blocks(f) => ("List<Map<String, dynamic>>".into(), !f.required),
        FieldAst::Custom(f) => (ts_to_dart(&f.ts_type), !f.required),
        _ => ("dynamic".into(), true),
    }
}

fn dart_from_json(name: &str, field: &FieldAst) -> String {
    match field {
        FieldAst::Datetime(f) | FieldAst::Timestamp(f) | FieldAst::Date(f) => {
            if f.required {
                format!("DateTime.parse(json['{}'])", name)
            } else {
                format!(
                    "json['{}'] != null ? DateTime.parse(json['{}']) : null",
                    name, name
                )
            }
        }
        // Declared String, but the column is NUMERIC and the wire may still send a JSON number,
        // where `as String` throws. toString() is correct for either shape.
        FieldAst::Money(f) => exact_from_json(name, f.required),
        FieldAst::Decimal(f) => exact_from_json(name, f.required),
        _ => {
            let (dart_type, nullable) = dart_type_of(field);
            if nullable {
                format!("json['{}'] as {}?", name, dart_type)
            } else {
                format!("json['{}'] as {}", name, dart_type)
            }
        }
    }
}

/// Decode for a kind declared String over a NUMERIC column.
fn exact_from_json(name: &str, required: bool) -> String {
    if required {
        format!("json['{}'].toString()", name)
    } else {
        format!("json['{}']?.toString()", name)
    }
}

fn dart_to_json(prop: &str, field: &FieldAst) -> String {
    match field {
        FieldAst::Datetime(f) | FieldAst::Timestamp(f) | FieldAst::Date(f) => {
            if f.required {
                format!("{}.toIso8601String()", prop)
            } else {
                format!("{}?.toIso8601String()", prop)
            }
        }
        _ => prop.to_string(),
    }
}

fn dart_array_elem(element_type: &str) -> &'static str {
    match element_type.to_uppercase().as_str() {
        "INTEGER" | "INT" | "INT4" | "SMALLINT" | "BIGINT" => "int",
        "FLOAT" | "FLOAT8" | "NUMERIC" | "DECIMAL" | "REAL" => "double",
        "BOOLEAN" | "BOOL" => "bool",
        _ => "String",
    }
}

fn ts_to_dart(ts: &str) -> String {
    match ts {
        "string" => "String".into(),
        "number" => "double".into(),
        "boolean" => "bool".into(),
        _ => "dynamic".into(),
    }
}

fn camel_case(s: &str) -> String {
    let mut parts = s.split('_');
    let first = parts.next().unwrap_or("").to_string();
    let rest: String = parts
        .map(|p| {
            let mut chars = p.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().to_string() + chars.as_str(),
            }
        })
        .collect();
    first + &rest
}
