use crate::parser::ast::{FieldAst, SchemaAst};
use anyhow::Result;

pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out = String::new();
    out.push_str("// Generated by supatype-engine — do not edit manually.\n");
    out.push_str("// Requires Swift 5.7+ / iOS 15+\n\n");
    out.push_str("import Foundation\n\n");

    for model in &ast.models {
        // Emit Swift enums for enum fields
        for (fname, f) in &model.fields {
            if let FieldAst::Enum(e) = f {
                let enum_name =
                    format!("{}{}", pascal_case(model.name.as_str()), pascal_case(fname));
                out.push_str(&format!("enum {}: String, Codable {{\n", enum_name));
                for v in &e.values {
                    out.push_str(&format!("    case {} = \"{}\"\n", to_swift_case(v), v));
                }
                out.push_str("}\n\n");
            }
        }

        out.push_str(&format!("struct {}: Codable {{\n", model.name));

        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let (swift_type, nullable) = swift_type_of(&model.name, name, fld);
            let prop_name = camel_case(name);
            if nullable {
                out.push_str(&format!("    var {}: {}?\n", prop_name, swift_type));
            } else {
                out.push_str(&format!("    var {}: {}\n", prop_name, swift_type));
            }
        }

        // Composite expansions
        for (_, fld) in &model.fields {
            match fld {
                FieldAst::Timestamps => {
                    out.push_str("    var createdAt: Date?\n");
                    out.push_str("    var updatedAt: Date?\n");
                }
                FieldAst::Publishable => {
                    out.push_str("    var status: String?\n");
                    out.push_str("    var publishedAt: Date?\n");
                    out.push_str("    var scheduledAt: Date?\n");
                }
                FieldAst::SoftDelete => {
                    out.push_str("    var deletedAt: Date?\n");
                }
                _ => {}
            }
        }

        // CodingKeys for snake_case ↔ camelCase
        out.push_str("\n    enum CodingKeys: String, CodingKey {\n");
        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let prop_name = camel_case(name);
            if prop_name != *name {
                out.push_str(&format!("        case {} = \"{}\"\n", prop_name, name));
            } else {
                out.push_str(&format!("        case {}\n", prop_name));
            }
        }
        out.push_str("    }\n");
        out.push_str("}\n\n");
    }

    Ok(out)
}

fn swift_type_of(model: &str, name: &str, field: &FieldAst) -> (String, bool) {
    match field {
        FieldAst::Text(f)
        | FieldAst::Email(f)
        | FieldAst::Url(f)
        | FieldAst::Ip(f)
        | FieldAst::Cidr(f)
        | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f)
        | FieldAst::Xml(f)
        | FieldAst::TsQuery(f)
        | FieldAst::TsVector(f)
        | FieldAst::Interval(f)
        | FieldAst::Uuid(f) => ("String".into(), !f.required),
        FieldAst::Slug(f) => ("String".into(), !f.required),
        FieldAst::Integer(f) | FieldAst::SmallInt(f) | FieldAst::Serial(f) => {
            ("Int".into(), !f.required)
        }
        FieldAst::Float(f) | FieldAst::Money(f) => ("Double".into(), !f.required),
        FieldAst::BigInt(f) | FieldAst::BigSerial(f) => ("Int64".into(), !f.required),
        FieldAst::Decimal(f) => ("Decimal".into(), !f.required),
        FieldAst::Boolean(f) => ("Bool".into(), !f.required),
        FieldAst::Datetime(f) | FieldAst::Timestamp(f) | FieldAst::Date(f) => {
            ("Date".into(), !f.required)
        }
        FieldAst::Enum(e) => {
            let enum_name = format!("{}{}", pascal_case(model), pascal_case(name));
            (enum_name, !e.required)
        }
        FieldAst::Json(_) => ("[String: Any]".into(), true),
        FieldAst::Array(a) => {
            let elem = swift_array_elem(&a.element_type);
            (format!("[{}]", elem), !a.required)
        }
        FieldAst::Image(f) | FieldAst::File(f) => ("[String: Any]".into(), !f.required),
        FieldAst::Geo(f) => ("[String: Any]".into(), !f.required),
        FieldAst::Vector(f) => ("[Double]".into(), !f.required),
        FieldAst::Blocks(f) => ("[[String: Any]]".into(), !f.required),
        FieldAst::Custom(f) => (ts_to_swift(&f.ts_type), !f.required),
        _ => ("Any".into(), true),
    }
}

fn swift_array_elem(element_type: &str) -> &'static str {
    match element_type.to_uppercase().as_str() {
        "INTEGER" | "INT" | "INT4" | "SMALLINT" | "BIGINT" => "Int",
        "FLOAT" | "FLOAT8" | "NUMERIC" | "DECIMAL" | "REAL" => "Double",
        "BOOLEAN" | "BOOL" => "Bool",
        _ => "String",
    }
}

fn ts_to_swift(ts: &str) -> String {
    match ts {
        "string" => "String".into(),
        "number" => "Double".into(),
        "boolean" => "Bool".into(),
        _ => "Any".into(),
    }
}

fn camel_case(s: &str) -> String {
    let mut parts = s.split('_');
    let first = parts.next().unwrap_or("").to_string();
    let rest: String = parts
        .map(|p| {
            let mut chars = p.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().to_string() + chars.as_str(),
            }
        })
        .collect();
    first + &rest
}

fn pascal_case(s: &str) -> String {
    s.split('_')
        .map(|seg| {
            let mut chars = seg.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().to_string() + chars.as_str(),
            }
        })
        .collect()
}

fn to_swift_case(s: &str) -> String {
    // Convert "some-value" or "some_value" to camelCase Swift identifier
    camel_case(&s.replace('-', "_"))
}
