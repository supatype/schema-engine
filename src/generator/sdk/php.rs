use crate::parser::ast::{FieldAst, SchemaAst};
use anyhow::Result;

pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out = String::new();
    out.push_str("<?php\n");
    out.push_str("// Generated by supatype-engine. Do not edit manually.\n");
    out.push_str("// Requires PHP 8.1+\n\n");
    out.push_str("declare(strict_types=1);\n\n");
    out.push_str("namespace Supatype\\Generated;\n\n");
    out.push_str("use DateTime;\n\n");

    for model in &ast.models {
        out.push_str(&format!("class {} {{\n", model.name));
        out.push_str("    public function __construct(\n");

        let mut params: Vec<String> = Vec::new();

        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let (php_type, nullable) = php_type_of(fld);
            let prefix = if nullable {
                format!("?{}", php_type)
            } else {
                php_type
            };
            let default = if nullable {
                " = null".to_string()
            } else {
                String::new()
            };
            params.push(format!(
                "        public readonly {} ${}{}",
                prefix, name, default
            ));
        }

        // Composite expansions
        for fld in model.fields.values() {
            match fld {
                FieldAst::Timestamps => {
                    params.push("        public readonly ?DateTime $created_at = null".into());
                    params.push("        public readonly ?DateTime $updated_at = null".into());
                }
                FieldAst::Publishable => {
                    params.push("        public readonly ?string $status = null".into());
                    params.push("        public readonly ?DateTime $published_at = null".into());
                    params.push("        public readonly ?DateTime $scheduled_at = null".into());
                }
                FieldAst::SoftDelete => {
                    params.push("        public readonly ?DateTime $deleted_at = null".into());
                }
                _ => {}
            }
        }

        out.push_str(&params.join(",\n"));
        if !params.is_empty() {
            out.push('\n');
        }
        out.push_str("    ) {}\n");
        out.push_str("}\n\n");
    }

    Ok(out)
}

fn php_type_of(field: &FieldAst) -> (String, bool) {
    match field {
        FieldAst::Text(f)
        | FieldAst::Email(f)
        | FieldAst::Url(f)
        | FieldAst::Ip(f)
        | FieldAst::Cidr(f)
        | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f)
        | FieldAst::Xml(f)
        | FieldAst::TsQuery(f)
        | FieldAst::TsVector(f)
        | FieldAst::Interval(f)
        | FieldAst::Uuid(f) => ("string".into(), !f.required),
        FieldAst::Slug(f) => ("string".into(), !f.required),
        FieldAst::Integer(f) | FieldAst::SmallInt(f) | FieldAst::Serial(f) => {
            ("int".into(), !f.required)
        }
        FieldAst::Float(f) => ("float".into(), !f.required),
        FieldAst::BigInt(f) | FieldAst::BigSerial(f) => ("int".into(), !f.required),
        // money and decimal are both NUMERIC. Exact digits, which no binary float holds, and
        // PHP has no decimal type, so the digits cross as a string for bcmath to consume.
        FieldAst::Money(f) => ("string".into(), !f.required),
        FieldAst::Decimal(f) => ("string".into(), !f.required),
        FieldAst::Boolean(f) => ("bool".into(), !f.required),
        FieldAst::Datetime(f) | FieldAst::Timestamp(f) | FieldAst::Date(f) => {
            ("DateTime".into(), !f.required)
        }
        FieldAst::Enum(e) => ("string".into(), !e.required),
        FieldAst::Json(_) => ("mixed".into(), true),
        FieldAst::Array(_) => ("array".into(), false),
        FieldAst::Image(f) | FieldAst::File(f) => ("array".into(), !f.required),
        FieldAst::Geo(f) => ("array".into(), !f.required),
        FieldAst::Vector(f) => ("array".into(), !f.required),
        FieldAst::Blocks(f) => ("array".into(), !f.required),
        FieldAst::Custom(f) => (ts_to_php(&f.ts_type), !f.required),
        _ => ("mixed".into(), true),
    }
}

fn ts_to_php(ts: &str) -> String {
    match ts {
        "string" => "string".into(),
        "number" => "float".into(),
        "boolean" => "bool".into(),
        _ => "mixed".into(),
    }
}
