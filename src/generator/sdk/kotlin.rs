use crate::parser::ast::{FieldAst, SchemaAst};
use anyhow::Result;

pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out = String::new();
    out.push_str("// Generated by supatype-engine — do not edit manually.\n\n");
    out.push_str("package supatype.generated\n\n");

    for model in &ast.models {
        // Emit plain enum classes for enum fields
        for (fname, f) in &model.fields {
            if let FieldAst::Enum(e) = f {
                let enum_name = format!("{}{}", model.name, pascal_case(fname));
                out.push_str(&format!("enum class {} {{\n", enum_name));
                for v in &e.values {
                    out.push_str(&format!("    {},\n", v.to_uppercase().replace('-', "_")));
                }
                out.push_str("}\n\n");
            }
        }

        out.push_str(&format!("data class {}(\n", model.name));

        // Collect required (no default) and optional (default = null) params separately.
        // Kotlin requires params with defaults to come after those without.
        let mut required_params: Vec<String> = Vec::new();
        let mut optional_params: Vec<String> = Vec::new();

        for (name, fld) in &model.fields {
            if matches!(
                fld,
                FieldAst::Relation(_)
                    | FieldAst::Timestamps
                    | FieldAst::Publishable
                    | FieldAst::SoftDelete
            ) {
                continue;
            }
            let (kt_type, nullable) = kotlin_type_of(&model.name, name, fld);
            let prop_name = camel_case(name);
            if nullable {
                optional_params.push(format!("    val {}: {}? = null", prop_name, kt_type));
            } else {
                required_params.push(format!("    val {}: {}", prop_name, kt_type));
            }
        }

        // Composite expansions always have defaults → optional
        for (_, fld) in &model.fields {
            match fld {
                FieldAst::Timestamps => {
                    optional_params.push("    val createdAt: String? = null".into());
                    optional_params.push("    val updatedAt: String? = null".into());
                }
                FieldAst::Publishable => {
                    optional_params.push("    val status: String? = null".into());
                    optional_params.push("    val publishedAt: String? = null".into());
                    optional_params.push("    val scheduledAt: String? = null".into());
                }
                FieldAst::SoftDelete => {
                    optional_params.push("    val deletedAt: String? = null".into());
                }
                _ => {}
            }
        }

        let params: Vec<String> = required_params.into_iter().chain(optional_params).collect();
        out.push_str(&params.join(",\n"));
        if !params.is_empty() {
            out.push('\n');
        }
        out.push_str(")\n\n");
    }

    Ok(out)
}

fn kotlin_type_of(model: &str, name: &str, field: &FieldAst) -> (String, bool) {
    match field {
        FieldAst::Text(f)
        | FieldAst::Email(f)
        | FieldAst::Url(f)
        | FieldAst::Ip(f)
        | FieldAst::Cidr(f)
        | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f)
        | FieldAst::Xml(f)
        | FieldAst::TsQuery(f)
        | FieldAst::TsVector(f)
        | FieldAst::Interval(f)
        | FieldAst::Uuid(f) => ("String".into(), !f.required),
        FieldAst::Slug(f) => ("String".into(), !f.required),
        FieldAst::Integer(f) | FieldAst::SmallInt(f) | FieldAst::Serial(f) => {
            ("Int".into(), !f.required)
        }
        FieldAst::Float(f) | FieldAst::Money(f) => ("Double".into(), !f.required),
        FieldAst::BigInt(f) | FieldAst::BigSerial(f) => ("Long".into(), !f.required),
        FieldAst::Decimal(f) => ("Double".into(), !f.required),
        FieldAst::Boolean(f) => ("Boolean".into(), !f.required),
        FieldAst::Datetime(f) | FieldAst::Timestamp(f) | FieldAst::Date(f) => {
            ("String".into(), !f.required)
        }
        FieldAst::Enum(e) => {
            let enum_name = format!("{}{}", model, pascal_case(name));
            (enum_name, !e.required)
        }
        FieldAst::Json(_) => ("Map<String, Any>".into(), true),
        FieldAst::Array(a) => {
            let elem = kotlin_array_elem(&a.element_type);
            (format!("List<{}>", elem), !a.required)
        }
        FieldAst::Image(f) | FieldAst::File(f) => ("Map<String, Any>".into(), !f.required),
        FieldAst::Geo(f) => ("Map<String, Any>".into(), !f.required),
        FieldAst::Vector(f) => ("List<Double>".into(), !f.required),
        FieldAst::Blocks(f) => ("List<Map<String, Any>>".into(), !f.required),
        FieldAst::Custom(f) => (ts_to_kotlin(&f.ts_type), !f.required),
        _ => ("Any".into(), true),
    }
}

fn kotlin_array_elem(element_type: &str) -> &'static str {
    match element_type.to_uppercase().as_str() {
        "INTEGER" | "INT" | "INT4" | "SMALLINT" => "Int",
        "BIGINT" => "Long",
        "FLOAT" | "FLOAT8" | "NUMERIC" | "DECIMAL" | "REAL" => "Double",
        "BOOLEAN" | "BOOL" => "Boolean",
        _ => "String",
    }
}

fn ts_to_kotlin(ts: &str) -> String {
    match ts {
        "string" => "String".into(),
        "number" => "Double".into(),
        "boolean" => "Boolean".into(),
        _ => "Any".into(),
    }
}

fn camel_case(s: &str) -> String {
    let mut parts = s.split('_');
    let first = parts.next().unwrap_or("").to_string();
    let rest: String = parts
        .map(|p| {
            let mut chars = p.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().to_string() + chars.as_str(),
            }
        })
        .collect();
    first + &rest
}

fn pascal_case(s: &str) -> String {
    s.split('_')
        .map(|seg| {
            let mut chars = seg.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().to_string() + chars.as_str(),
            }
        })
        .collect()
}
