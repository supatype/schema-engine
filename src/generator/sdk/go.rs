use anyhow::Result;
use crate::parser::ast::{FieldAst, SchemaAst};

pub fn generate(ast: &SchemaAst) -> Result<String> {
    let mut out = String::new();
    out.push_str("// Generated by supatype-engine — do not edit manually.\n\n");
    out.push_str("package supatype\n\n");
    out.push_str("import \"time\"\n\n");

    for model in &ast.models {
        out.push_str(&format!("// {} maps to the {} Postgres table.\n", model.name, model.table_name));
        out.push_str(&format!("type {} struct {{\n", model.name));

        for (name, fld) in &model.fields {
            if matches!(fld, FieldAst::Relation(_)) { continue; }
            if matches!(fld, FieldAst::Timestamps | FieldAst::Publishable | FieldAst::SoftDelete) { continue; }
            let (go_type, nullable) = go_type_of(fld);
            let json_tag = to_snake_case(name);
            let field_name = pascal_case(name);
            if nullable {
                out.push_str(&format!("\t{} *{} `json:\"{},omitempty\"`\n", field_name, go_type, json_tag));
            } else {
                out.push_str(&format!("\t{} {} `json:\"{}\"`\n", field_name, go_type, json_tag));
            }
        }

        // Composite expansions
        for (_, fld) in &model.fields {
            match fld {
                FieldAst::Timestamps => {
                    out.push_str("\tCreatedAt *time.Time `json:\"created_at,omitempty\"`\n");
                    out.push_str("\tUpdatedAt *time.Time `json:\"updated_at,omitempty\"`\n");
                }
                FieldAst::Publishable => {
                    out.push_str("\tStatus *string `json:\"status,omitempty\"`\n");
                    out.push_str("\tPublishedAt *time.Time `json:\"published_at,omitempty\"`\n");
                    out.push_str("\tScheduledAt *time.Time `json:\"scheduled_at,omitempty\"`\n");
                }
                FieldAst::SoftDelete => {
                    out.push_str("\tDeletedAt *time.Time `json:\"deleted_at,omitempty\"`\n");
                }
                _ => {}
            }
        }

        out.push_str("}\n\n");
    }

    Ok(out)
}

fn go_type_of(field: &FieldAst) -> (String, bool) {
    match field {
        FieldAst::Text(f) | FieldAst::Email(f) | FieldAst::Url(f)
        | FieldAst::Ip(f) | FieldAst::Cidr(f) | FieldAst::Macaddr(f)
        | FieldAst::Bytes(f) | FieldAst::Xml(f)
        | FieldAst::TsQuery(f) | FieldAst::TsVector(f)
        | FieldAst::Interval(f) | FieldAst::Uuid(f) => ("string".into(), !f.required),
        FieldAst::Slug(f) => ("string".into(), !f.required),
        FieldAst::Integer(f) | FieldAst::SmallInt(f) | FieldAst::Serial(f) => ("int32".into(), !f.required),
        FieldAst::Float(f) | FieldAst::Money(f) => ("float64".into(), !f.required),
        FieldAst::BigInt(f) | FieldAst::BigSerial(f) => ("int64".into(), !f.required),
        FieldAst::Decimal(f) => ("string".into(), !f.required),
        FieldAst::Boolean(f) => ("bool".into(), !f.required),
        FieldAst::Datetime(f) | FieldAst::Timestamp(f) => ("time.Time".into(), !f.required),
        FieldAst::Date(f) => ("time.Time".into(), !f.required),
        FieldAst::Enum(e) => ("string".into(), !e.required),
        FieldAst::Json(_) => ("interface{}".into(), true),
        FieldAst::Array(a) => {
            let elem = go_array_elem(&a.element_type);
            (format!("[]{}", elem), !a.required)
        }
        FieldAst::Image(f) | FieldAst::File(f) => ("map[string]interface{}".into(), !f.required),
        FieldAst::Geo(f) => ("map[string]interface{}".into(), !f.required),
        FieldAst::Vector(f) => ("[]float64".into(), !f.required),
        FieldAst::Blocks(f) => ("[]map[string]interface{}".into(), !f.required),
        FieldAst::Custom(f) => (ts_to_go(&f.ts_type), !f.required),
        _ => ("interface{}".into(), true),
    }
}

fn go_array_elem(element_type: &str) -> &'static str {
    match element_type.to_uppercase().as_str() {
        "INTEGER" | "INT" | "INT4" | "SMALLINT" => "int32",
        "BIGINT" => "int64",
        "FLOAT" | "FLOAT8" | "NUMERIC" | "DECIMAL" | "REAL" => "float64",
        "BOOLEAN" | "BOOL" => "bool",
        _ => "string",
    }
}

fn ts_to_go(ts: &str) -> String {
    match ts {
        "string" => "string".into(),
        "number" => "float64".into(),
        "boolean" => "bool".into(),
        _ => "interface{}".into(),
    }
}

fn to_snake_case(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(c.to_lowercase().next().unwrap());
    }
    out
}

fn pascal_case(s: &str) -> String {
    s.split('_').map(|seg| {
        let mut chars = seg.chars();
        match chars.next() {
            None => String::new(),
            Some(c) => c.to_uppercase().to_string() + chars.as_str(),
        }
    }).collect()
}
